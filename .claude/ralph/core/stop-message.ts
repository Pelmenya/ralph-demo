// Структурированный стоп «PR оставлен человеку» (#289).
//
// Симптом карточки: когда петля останавливается (⛔/🏁/breaker/DEADMAN), в ralph.log и
// в Telegram уходит один и тот же маркер независимо от причины — красный локальный чек (#281),
// красный чек площадки (#269), спорное ревью, конфликт веток, дерево не на нужной ветке.
// Разбор ложится на вахту: GetMergeChecks → лог куба → сравнение с локальным гейтом.
//
// Модуль ЧИСТЫЙ (тот же жанр, что api-limit.ts/spawn-failure.ts): он не решает, ЧТО
// произошло, — это знает вызывающий код (gate.ts/phase-branch.ts/orchestrator.ts), —
// а только форматирует ОДНУ строку для лога и для Telegram-нотифаера, чтобы оба канала
// несли одинаковый текст (см. руководящий инвариант №10 CLAUDE.md ядра: форматы строк —
// контракт). Причина — из закрытого перечня: незнакомая причина не компилируется, а не
// проезжает молча как вольная строка.

export type TStopReason =
    | 'platform-check-red'
    | 'gate-red'
    | 'gate-tool-failure'
    | 'review-dispute'
    | 'review-no-verdict'
    | 'blocked-unconfirmed'
    | 'main-conflict'
    | 'main-sync-failed'
    | 'head-diverged'
    | 'session-unpushed'
    | 'tree-dirty'
    | 'intent-unknown'
    | 'intent-rejected'
    | 'merge-unknown'
    | 'merge-failed'
    | 'stage-journal'
    | 'forge-unreadable'
    | 'issue-format'
    | 'guard-probe'
    | 'breaker'
    | 'deadman'
    | 'unknown';

export type TStopMessageInput = {
    reason: TStopReason;
    // Что раннер уже выяснил: имя куба, упавший кейс, файл спора, счётчик попыток.
    diagnosis: string;
    // Что именно решить человеку: «смерджить руками», «пустой коммит и повтор», «снять
    // карточку с вехи» — а не общее «разберись».
    question: string;
};

// Заголовок причины на русском — для человека, который не помнит наизусть enum.
//
// Экспортируется РАДИ ТЕСТА (ревью #289): `Object.keys(REASON_TITLES)` — единственный
// источник перечня, который нельзя забыть расширить. Ручная копия массива в тесте
// давала бы ложную гарантию: девятое значение в `TStopReason` оставило бы массив из
// восьми валидным, и `it.each` остался бы зелёным. Здесь же `Record<TStopReason, …>`
