/**
 * Собирает единую строку «причина + диагноз + вопрос» — общую для лога и для
 * Telegram-нотифаера (вызывающий код передаёт РЕЗУЛЬТАТ этой функции в оба места, а не
 * строит два разных текста из одних переменных, как было до #289).
 *
 * Возвращает именно ФРАГМЕНТ (без ведущего ⛔/эмодзи и без «PR оставлен человеку») —
 * вызывающий код склеивает его со своим заголовком, потому что заголовок различается по
 * месту стопа (PR / фаза / карточка), а причина-диагноз-вопрос — нет.
 */
export function formatStopMessage({ reason, diagnosis, question }: TStopMessageInput): string {
    const title = REASON_TITLES[reason];
    // Точка в конце диагноза — забота ЭТОГО модуля, а не каждого вызывающего: формат
    // строки он и так держит целиком, а без разделителя диагноз без своей точки
    // («чек форжа не дал вердикта») слипался со следующим полем в одну фразу
    // «диагноз: … вопрос человеку: …» (ревью #289).
    const diagnosisText = diagnosis.trim();
    const withStop = /[.!?…:;]$/u.test(diagnosisText) ? diagnosisText : `${diagnosisText}.`;
    return (
        `причина: ${title} (${reason}). ` +
        `диагноз: ${withStop} ` +
        `вопрос человеку: ${question.trim()}`
    );
}
