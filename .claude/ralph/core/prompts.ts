// #269: подсказка для случая, когда локальный гейт зелёный, а чек форжа красный. Это не
// украшение промпта, а единственное, что отличает такую сессию от обычной чини-сессии:
// «воспроизведи чек локально» здесь заведомо не сработает, и без указания искать разницу
// СРЕД модель полчаса гоняет зелёный набор и объявляет отказ невоспроизводимым.
//
// Текст НАМЕРЕНИЕ, а не перечень мест: конкретика («рабочий каталог `/repo`», имена
// переменных окружения площадки) уехала в конфиг проекта параметром `forgeEnvHint` —
// правка по ревью #269. В ядре она нарушала инвариант #45, а барьер `core-purity` её
// пропускал из-за `\b` перед подчёркиванием — то есть строка прошла не потому, что была
// законна, а потому, что барьер был слеп к этой форме (барьер тоже расширен).
const FORGE_ONLY_HINT =
    'ВАЖНО: локальный набор на этой же голове ЗЕЛЁНЫЙ — отказ живёт только в контейнере ' +
    'форжа, и «воспроизвести локально» его не выйдет: ищи разницу СРЕД, а не дефект, ' +
    'который виден на хосте. ';

// Самолечение гейта: чек упал на точном sha PR-головы, чинит причину отдельная сессия.
export function buildGateHealPrompt({
    requestsPath,
    branch,
    checkName,
    checkCmd,
    excerpt,
    gateCmdList,
    forgeOnly = false,
    forgeEnvHint,
}: GateHealPromptParams): string {
    // #269-ревью: при `forgeOnly` в `checkCmd` лежит АДРЕС упавшего куба («куб «test»
    // прогона 356»), а не то, что можно выполнить, — и префикс «команда:» делал промпт
    // ложным. Рядом в том же тексте перечислен `gateCmdList` из настоящих команд, и
    // смешение двух смыслов в одном поле путало сессию сильнее, чем помогало.
    const where = forgeOnly ? `(${checkCmd})` : `(команда: ${checkCmd})`;
    // #269-ревью: вторая половина фразы ОТМЕНЯЛА подсказку строкой выше — «воспроизвести
    // локально не выйдет» и тут же «воспроизведи чек локально». Из двух указаний модель
    // берёт последнее, то есть ровно то, от которого её отговаривают.
    const how = forgeOnly
        ? `Дерево уже стоит на ветке ${branch} — найди и исправь ПРИЧИНУ чтением кода ` +
          'и сравнением сред; локальный прогон здесь ничего не покажет.'
        : `Дерево уже стоит на ветке ${branch} — воспроизведи чек локально, ` +
          'найди и исправь ПРИЧИНУ.';
    const hint = forgeOnly
        ? `${FORGE_ONLY_HINT}${forgeEnvHint ? `${forgeEnvHint.trim()} ` : ''}`
        : '';
    return (
        `Гейт мерджа фазы упал на чеке ${checkName} ${where} в ветке ${branch}. ` +
        `Хвост вывода ошибки: ${excerpt}. ${hint}${how} Затем добейся зелёного всего набора: ${gateCmdList}. ${COMMIT_RULE} Закоммить ` +
        `исправление в ${branch} и запушь в origin. ${intentsRule(requestsPath)} Если причина не чинится кодом ` +
        `автономно — запиши намерение pr-block с объяснением. ${HOLD_RULE}`
    );
}

// #110: обещание про карточки собирается из ДЕЙСТВУЮЩЕГО порога `review.backlogSeverityFloor`,
// а не выписано константой. Пока фраза была фиксированной, промпт обещал карточку за каждый
// ⚪ nit, а фильтр порога заводить её отказывался — сессия тратила ходы на находки, которые
// петля молча отбрасывала, а человек искал карточки, которых нет. Это тот же класс, что
// враньё в строке лога: сообщения ядра обязаны быть правдой (`core-purity.test.ts`).
//
// Порог сюда приходит параметром, а не читается из конфига: функции модуля чистые, и
// подстановка значения — единственный способ, при котором текст не разъедется с ключом
// при смене значения.
function backlogPromise(severityFloor: FixSeverity | undefined): string {
    if (!severityFloor) {
        return 'minor и nit петля заведёт карточками и мердж задерживать не будет';
    }
    return (
        `находки не мельче уровня «${severityFloor}» петля заведёт карточками и мердж ` +
        'задерживать не будет, а всё, что мельче, останется комментарием на PR — карточкой ' +
        'оно не станет'
    );
}

export type FixReviewPromptParams = {
    // Канал намерений — фактический путь прогона (канон, задача 22).
    requestsPath: string;
    branch: string;
    allowNames: string;
    // Дифф ИМЕННО правок (база — голова ветки до сессии правок), а не всей фазы.
    fixDiffContext: string;
    commentsContext?: string;
    // Номер прохода и потолок — ОДНА И ТА ЖЕ величина: проходы, принёсшие НОВЫЕ
    // blocker/major (их считает потолок лестницы). Круги без новых блокеров сюда не
    // попадают намеренно: пара «проход 5 из 3» читается моделью как «лимит уже превышен,
    // можно не стараться», а человеком — как сорванный барьер (ревью #625).
    pass: number;
    maxPasses: number;
    // Действующий порог `review.backlogSeverityFloor`. Не задан — прежнее обещание:
    // карточка заводится на любую находку.
    severityFloor?: FixSeverity;
};

// #625: ревью ПРАВОК — второй проход, который идёт после ЛЮБЫХ правок по ревью, а не
// только когда остались блокеры. Предмет прохода — дифф самих правок: они пишутся быстро,
// под конец сессии и без собственного ревью, и на разборе 14.08 половина дефектов фазы
// нашлась именно в них.
//
// Промпт намеренно НЕ просит перепроверять PR целиком: это уже сделал первый проход, а
// повтор той же работы жёг бы бюджет и приносил бы те же замечания заново — то есть ровно
// пинг-понг, от которого лестница и защищается.
export function buildFixReviewPrompt({
    requestsPath,
    branch,
    allowNames,
    fixDiffContext,
    commentsContext,
    pass,
    maxPasses,
    severityFloor,
}: FixReviewPromptParams): string {
    return (
        `Найди последний открытый PR из ветки ${branch} в main. По его замечаниям уже прошла сессия ` +
        `правок — отревьюй ИМЕННО ЭТИ ПРАВКИ (проход ${String(pass)} из ${String(maxPasses)} — ` +
        `счёт идёт по проходам, нашедшим НОВЫЕ blocker/major). ` +
        `Дифф правок приложен ниже; PR целиком заново не пересматривай — он уже отревьюен, ` +
        `предмет этого прохода в том, не сломали ли что-нибудь сами правки: убитое поведение, ` +
        `потерянный отказ, тест, который больше не может упасть, правка мимо смысла замечания.` +
        `${fixDiffContext}${commentsContext ?? ''} ` +
        `Комментарии собрала петля и оставила ТОЛЬКО от доверенных авторов (${allowNames}) — они здесь ` +
        `для того, чтобы понять, что именно правка должна была починить; других ты не видишь. ` +
        `${intentsRule(requestsPath)} ` +
        `На КАЖДУЮ найденную в правках проблему — намерение pr-comment С ЯКОРЕМ (path + line) и ` +
        `с пометкой серьёзности строго в формате 🔴 [blocker] / 🟠 [major] / 🟡 [minor] / ⚪ [nit]. ` +
        `Серьёзность здесь — решение о мердже: blocker и major вернут фазу на ещё один круг правок, ` +
        `${backlogPromise(severityFloor)}. Ставь метку по цене ошибки, ` +
        `а не по вежливости. Замечание, которое уже предъявлялось и было отклонено с обоснованием, ` +
        `повторяй, только если считаешь отклонение неверным по существу: петля считает такие повторы ` +
        `спором и после второго заводит карточку с обеими позициями. Правки чистые — так и напиши ` +
        `коротким pr-comment без якоря. ${HOLD_RULE}`
    );
}

export type FixArbiterPromptParams = {
    branch: string;
    fixDiffContext: string;
    requestsPath: string;
    // Тот же ключ, что и у ревью правок: обещание арбитра про карточки обязано совпадать
    // с действующим порогом — арбитр тоже размечает мелочь и тоже рассчитывает, что она
    // куда-то доедет.
    severityFloor?: FixSeverity;
};

// #625, ступень 5: независимый арбитр на исчерпании потолка проходов. Вместо стопа
// человеку — сильнейшая модель БЕЗ ИСТОРИИ предыдущих проходов.
//
// «Без истории» — не экономия контекста, а суть приёма: 18.08 на Codex шесть ревью подряд
// согласились друг с другом и внесли регрессию, а нашёл её седьмой проход, который прежних
// выводов не видел. Поэтому здесь НЕТ ни commentsContext, ни перечня спорных замечаний:
// арбитр смотрит на код правок и отвечает на свой вопрос сам.
export function buildFixArbiterPrompt({
    branch,
    fixDiffContext,
    requestsPath,
    severityFloor,
}: FixArbiterPromptParams): string {
    return (
        `Ты независимый арбитр. По PR ветки ${branch} уже прошло несколько кругов «ревью → правки», ` +
        `и они не сошлись. Выводы предыдущих проходов тебе НЕ показаны намеренно: согласившиеся друг ` +
        `с другом ревью пропускают ровно те дефекты, которые видит незамутнённый взгляд.` +
        `${fixDiffContext} ` +
        `Твой вопрос ровно один: есть ли в ЭТОМ диффе правок проблема, из-за которой его нельзя ` +
        `мерджить, — сломанное поведение, потерянный отказ, дыра безопасности, правка, противоречащая ` +
        `собственному коду рядом. Читай окружающий код по месту правок, не только дифф. ` +
        `${intentsRule(requestsPath)} ` +
        `Нашёл такую проблему — намерение pr-block с описанием и намерение pr-comment с якорем ` +
        `(path + line) и пометкой 🔴 [blocker] либо 🟠 [major]. Не нашёл — pr-block НЕ пиши и оставь ` +
        `коротким pr-comment без якоря, что блокирующего в правках не видишь; спорные мелочи, если ` +
        `они есть, помечай 🟡 [minor] / ⚪ [nit] — ${backlogPromise(severityFloor)}. ` +
        `Отвечай по коду, а не по тому, что «раз спорили, значит что-то есть». ${HOLD_RULE}`
    );
}
