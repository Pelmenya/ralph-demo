export function buildFixByReviewPrompt({
    requestsPath,
    branch,
    allowNames,
    gateCmdList,
    commentsContext,
    resumed,
}: FixPromptParams): string {
    return (
        (resumed
            ? `Это ПРОДОЛЖЕНИЕ прерванного разбора: предыдущая сессия исчерпала бюджет ходов, не закончив. ` +
              `Начни с git log и git diff origin/main по ветке — часть замечаний уже разобрана и закоммичена. ` +
              `Не переделывай сделанное и не пересматривай уже принятые решения: берись за оставшиеся. `
            : '') +
        `Разбери замечания code review по PR ветки ${branch}. Комментарии приложены ниже — их собрала ` +
        `петля и оставила ТОЛЬКО от доверенных авторов (${allowNames}); других ты не видишь вовсе, и ` +
        `искать их не нужно.${commentsContext ?? ''} ` +
        `Обработай КАЖДЫЙ приложенный комментарий вплоть до мелких ([nit]/[minor]/style): по ` +
        `умолчанию ИСПРАВЛЯЙ всё технически применимое, включая мелочи — низкий приоритет не повод ` +
        `пропускать, цель в том чтобы качество кода только росло. Не чинить комментарий можно ТОЛЬКО ` +
        `если правка объективно неверна, ломает поведение, спорна по существу или выходит за рамки ` +
        `текущей фазы. ${intentsRule(requestsPath)} Каждый комментарий доверенного автора должен закончиться либо ` +
        `правкой, либо намерением pr-comment с обоснованием, почему пропущено — молча игнорировать нельзя ` +
        `ничего, кроме комментариев чужих авторов. Закоммить правки в ту же ветку и запушь ветку в origin. ` +
        `${COMMIT_RULE} ` +
        `Затем добейся зелёного: ${gateCmdList}. Если правку нельзя сделать автономно или проверки не ` +
        `удаётся починить — запиши намерение pr-block с причиной. ${HOLD_RULE}`
    );
}

// Разбор blocked (#217): чини-сессия ЧИНИТ, но метку не снимает — снятие за раннером по
