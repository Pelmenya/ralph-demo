// #16/#18/#98: АДРЕС накопительной вехи для карточек, заводимых петлёй по ходу работы.
//
// Модуль вынесен из review-of-fixes.ts (#98, ревью границ на PR !49): назначение вехи —
// канал, ОБЩИЙ для двух независимых потребителей (лестница ревью правок и намерение
// `new-issue` кодер-сессии), а `review-of-fixes.ts` по контракту `CLAUDE.md` — чистая
// арифметика ЛЕСТНИЦЫ, к выбору вехи отношения не имеющая.
//
// ЧТО СЮДА НЕ ПЕРЕЕХАЛО, и почему это важно (ревью правок #98). Первая редакция забрала
// с собой и `staleLadderCards` — «она мутирует те же карточки». Обоснование было ложным
// дважды: функция ничего не мутирует (отбирает номера), а карточку лестницы она узнаёт
// ПО ЗАГОЛОВКУ — то есть по признаку авторства, который живёт в `review-of-fixes.ts`.
// Ценой был импорт префиксов сюда, и канал `new-issue` кодер-сессии, к лестнице
// отношения не имеющий, начинал зависеть от её арифметики транзитивно — связность не
// убиралась, а переставлялась. Поэтому чистка осталась там же, где префиксы, а этот
// модуль — НАСТОЯЩИЙ лист: ноль импортов, как и `review-of-fixes.ts`.
//
// TS без билд-шага: erasable-only синтаксис (нативный type stripping Node 24).

// Потолок наполнения по умолчанию. Пять — не круглое число, а то же правило, что у любой
// вехи, отдаваемой раннеру фазой: фаза = один PR, и очередь прямо задаёт размер диффа.
// Проверено ценой: веха из семнадцати задач дала шесть с половиной тысяч строк в одном PR,
// после чего сошлось всё сразу — предел намерений, дефекты от взаимодействия правок и
// разбор, потребовавший человека.
export const BACKLOG_MILESTONE_CAP = 5;

export type BacklogTarget = { milestone: string; index: number; count: number };

// Статус вехи и её наполнение — РАЗНЫЕ вопросы, и #65 стоил того, что спрашивался только
// второй. Разобранный том закрыт, все его карточки закрыты, открытых в нём ноль — и для
// выбора по наполнению это «самая свободная веха списка»: находки ехали в закрытую веху,
// где их не видит ни доска, ни ревизия бэклога, а лог бодро писал «адрес запрошен».
// Чем аккуратнее разобран том, тем охотнее в него ложились новые карточки.
//
// Косвенный признак («ноль открытых и хоть одна закрытая — значит разобран») отвергнут:
// он ломается на томе, где одну карточку закрыли руками до разбора, — такой том открыт и
// годен. Поэтому статус спрашивается у форжа прямо (`isMilestoneOpen` шва), а `isOpenFn`
// обязателен: канал адреса, забывший про статус, не соберётся.
export function pickBacklogMilestone({
    candidates,
    currentPhase,
    cap,
    countOpenFn,
    isOpenFn,
    from = 0,
}: {
    candidates: readonly string[];
    currentPhase: string;
    cap: number;
    countOpenFn: (milestone: string) => number | null;
    // null — «статус не прочитан». Кандидат пропускается, как при непрочитанном
    // наполнении: принять неизвестный статус за открытый значило бы возвращать #65 на
    // любом отказе чтения.
    isOpenFn: (milestone: string) => boolean | null;
    from?: number;
}): BacklogTarget | null {
    for (let i = Math.max(0, from); i < candidates.length; i += 1) {
        const milestone = candidates[i];
        // Наполнение вехи текущей фазы не спрашиваем вовсе: она отвергнута правилом, а
        // лишний запрос к форжу оплачивался бы на каждой карточке круга.
        if (milestone === currentPhase) continue;
        // Статус — ДО наполнения: у лестницы подсчёт заодно чистит протухшее, то есть
        // мутирует карточки, и делать это в вехе, которая не кандидат, незачем.
        if (isOpenFn(milestone) !== true) continue;
        // null — «не сосчитали». Ревью PR !6: считать его нулём нельзя двояко. У площадки
        // самая частая причина отказа чтения в том, что вехи там нет вовсе (резолв имени
        // бросает) — адресовать карточку в неё бессмысленно. А главное, потолок при таком
        // допущении перестаёт быть барьером: одно неотвеченное чтение делало бы годной
        // любую, сколь угодно переполненную веху. Не сосчитали — берём следующую.
        const count = countOpenFn(milestone);
        if (count === null || count >= cap) continue;
        return { milestone, index: i, count };
    }
    return null;
}

// Нормализация ключа `review.backlogMilestone`: имя, список имён или ничего.
//
// Ключ описан как «строка ИЛИ массив строк» и валидируется на старте
// (`config-profile.ts`), но читают его два независимых места — лестница ревью и канал
// намерений кодер-сессии. Своя копия развилки в каждом означала бы, что однажды они
// разойдутся в мелочи (пустая строка, пробел), а расхождение здесь тихое: карточка просто
// поедет без адреса.
export function backlogCandidates(value: string | readonly string[] | undefined): string[] {
    return (Array.isArray(value) ? value : [value]).filter(
        (m): m is string => typeof m === 'string' && m.trim() !== '',
    );
}

// АДРЕС карточек, заводимых петлёй по ходу работы, — ленивый и не более раза на батч.
//
// Почему фабрика, а не функция: искать адрес до первой карточки незачем (обычная сдача не
// заводит ни одной и не платит за это ни одним запросом к форжу), а между карточками
// ОДНОГО батча наполнение вехи нужно помнить — иначе потолок обходится сам собой.
//
// Пересчитывать наполнение перед КАЖДОЙ карточкой отвергнуто (ревью порта): между чтением
// и заведением зазор остаётся при любом числе пересчётов — атомарности на стороне форжа
// нет, — так что гонка этим не закрывается, а запрос платится за каждую находку. Цена
// промаха несоразмерна: веха окажется на карточку-другую полнее потолка, и человек
// разложит их, когда будет отдавать её партией.
//
// Чистка протухшего сюда НЕ входит намеренно: она мутирует чужие карточки и принадлежит
// вызывающему, а не всякому, кому нужен адрес. Кому она нужна — заворачивает её в свой
// `countOpenFn`, как это делает цикл сдачи.
export function createBacklogAddress({
    candidates,
    cap,
    currentPhase,
    countOpenFn,
    isOpenFn,
    logFn,
    what,
}: {
    candidates: readonly string[];
    cap: number;
    currentPhase: string;
    countOpenFn: (milestone: string) => number | null;
    isOpenFn: (milestone: string) => boolean | null;
    logFn: (line: string) => void;
    // Чьи это карточки — только для строки лога. Человеку нужно знать, ЧТО именно поехало
    // без адреса: у лестницы и у кодер-сессии разная цена потери.
    what: string;
}): () => string | undefined {
    // `undefined` — «ещё не искали», `null` — «искали, не нашли».
    let target: BacklogTarget | null | undefined;
    let logged = false;
    return () => {
        if (candidates.length === 0) return undefined;
        if (target === undefined) {
            target = pickBacklogMilestone({
                candidates,
                currentPhase,
                cap,
                countOpenFn,
                isOpenFn,
            });
        }
        // Веха добилась до потолка карточками ЭТОГО ЖЕ батча — дальше ищем с её места:
        // перебирать уже отвергнутых заново значит платить за их наполнение по второму разу.
        if (target && target.count >= cap) {
            target = pickBacklogMilestone({
                candidates,
                currentPhase,
                cap,
                countOpenFn,
                isOpenFn,
                from: target.index + 1,
            });
        }
        if (!target) {
            // Молчать нельзя: ключ конфига задан, а карточки едут без адреса. Причин четыре —
            // вехи переполнены, закрыты (тома разобраны, пора завести следующий),
            // единственная названная и есть текущая фаза, либо их статус или наполнение не
            // читается (чаще всего потому, что вехи на площадке нет). Все четыре чинит
            // человек, но узнать о них ему неоткуда, кроме лога.
            if (!logged) {
                logged = true;
                logFn(
                    `⚠ Накопительной вехи для ${what} не нашлось ` +
                        `(кандидаты: ${candidates.join(', ')}; потолок ${String(cap)}; ` +
                        'закрытые и непрочитанные пропущены) — ' +
                        'карточки заводятся без адреса.',
                );
            }
            return undefined;
        }
        target.count += 1;
        return target.milestone;
    };
}
