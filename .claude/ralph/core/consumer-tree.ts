/**
 * Кто держит дерево потребителя актуальным (канон, задача 28).
 *
 * Задача 23 заякорила пути скриптов потребителя к `consumerRoot`: инструмент берётся из
 * дерева ПОТРЕБИТЕЛЯ, а не из ветки фазы, — иначе петля исполняла бы версию скрипта,
 * написанную той самой сессией, работу которой она надзирает. Якорь остаётся; вопрос,
 * который он открыл, — другой: **это дерево раннер не обновлял вовсе**. Скрипт, добавленный
 * фазовым PR, там не появлялся, вызов оставался fail-open, и «работает ли синк доски»
 * зависело от того, когда человек последний раз делал `pull` руками.
 *
 * Контракт: **обновляет раннер, сразу после мерджа фазы, best-effort и только вперёд**.
 * Отвергнуты два соседних варианта:
 *
 *   - «брать артефакты из дерева работы» — снимает якорь задачи 23 вместе с его смыслом:
 *     сессия, правящая свой же инструмент, получила бы его неотревьюенную версию в том же
 *     прогоне. Стабильность инструмента — свойство управляемости, а не удобства;
 *   - «обновление — работа потребителя» — честно, но враждебно AFK: раннер и заводился
 *     ради прогонов без человека, а такой контракт требует человека МЕЖДУ фазами, то есть
 *     ровно в том окне, ради которого он работает.
 *
 * Момент выбран не «когда угодно, лишь бы почаще»: обновление идёт МЕЖДУ фазами. Внутри
 * фазы версия инструмента обязана стоять на месте (та же задача 23), а после мерджа
 * актуальная версия — ровно та, что только что прошла ревью и гейт.
 *
 * Дерево потребителя — дерево ЧЕЛОВЕКА, и это задаёт все ограничения ниже: не трогаем
 * грязное, не трогаем чужую ветку, не сливаем ничего, кроме fast-forward, и никогда не
 * разрешаем конфликтов за него. Каждый отказ называется в логе вместе с командой, которой
 * человек закончит сам, — «не смог» без адреса неотличимо от «не понадобилось».
 *
 * **Требуется git ≥ 2.29** — с него есть `--no-write-fetch-head`. На более старом fetch
 * откажет с `unknown option`, и обновление не состоится; отказ при этом ГРОМКИЙ — строка
 * с текстом git в логе, а не молчаливый пропуск, поэтому отдельной ранней проверки версии
 * здесь нет (ревью, 5-й проход).
 *
 * **Остаточная гонка названа честно.** Дерево человека он же и переключает, а атомарного
 * «слей в HEAD, только если HEAD — это `main`» у git нет вовсе. Ветка сверяется дважды —
 * до fetch и вплотную к слиянию — и ещё раз после него, но человек, успевший уйти на свою
 * ветку и вернуться на `main` внутри этого промежутка, не виден ни одной из трёх сверок.
 * То же и с чистотой дерева: она сверяется дважды, но мгновение между второй сверкой и
 * слиянием остаётся. Git прикроет только те пути, которые слияние обязано перезаписать, —
 * правку в СОСЕДНЕМ файле он не заметит и ветку перемотает (ревью, 6-й проход). Цена
 * остатка мала, но она не ноль, и делать вид, что ноль, здесь нельзя.
 * Отсюда два следствия: окно сужено до предела, какой доступен без сериализации с
 * человеком, а пост-сверка печатает ФАКТЫ (откуда ушли, что слито), а не команду отката —
 * `reset --hard`, выданный вслепую, откатил бы не ту ветку (ревью, 3-й и 4-й проходы).
 *
 * Чего эта функция НЕ делает, и это решение, а не упущение:
 *
 *   - **не рекурсирует в подмодули.** Каталог продукта у потребителя — подмодуль внутри
 *     `consumerRoot`; `--recurse-submodules` подменил бы код продукта под работающей
 *     петлёй. Ревизия продукта меняется lifecycle-операцией launcher'а (`./ralph update`),
 *     где у неё есть транзакция и рестарт, а не побочкой обновления соседнего дерева;
 *   - **не перечитывает `ralph.config.json`.** Петля исполняет конфиг, загруженный при
 *     старте; приехавшая правка конфига вступит в силу с рестартом. Это отдельная задача
 *     («фикс ядра не действует до перезапуска»), и делать вид, что обновление файла на
 *     диске её решает, было бы хуже молчания.
 *
 * TS-модуль без билд-шага: исполняется нативным type stripping Node 24 (erasable-only).
 */
import { gitNetworkOpts } from '../shared/ralph-util.ts';
import type { ShArgvFn } from '../shared/ralph-util.ts';
import type { TResolvedRoots } from './roots.ts';

/** Чем кончилось обновление. Решение вызывающего по каждому исходу — только лог. */
export type TConsumerTreeKind =
    'no-roots' | 'same-tree' | 'dirty' | 'off-main' | 'failed' | 'updated';

export type TConsumerTreeDeps = {
    /** Тот же контракт, что у `shArgv` ядра: argv плюс опции запуска (нам нужен `env`). */
    runArgvFn: ShArgvFn;
    logFn: (msg: string) => void;
    /** Окружение вызывающего. Навязывающие репозиторий переменные снимаются здесь же. */
    env?: NodeJS.ProcessEnv;
};

/**
 * Ветка потребителя — `main`, как и везде в ядре (`origin/main` у дерева раннера, #77).
 * Имя не приезжает из конфига намеренно: раннер и так строит все фазы от `origin/main`,
 * и вторая точка настройки завела бы раскладку, где эти два «главных» ref'а расходятся.
 * Дальше по коду это имя используется ДВАЖДЫ и по-разному: как имя локальной ветки, на
 * которой обязано стоять дерево, и как имя ветки на `origin`, которую фетчим. Сливается
 * при этом свой ref — см. довод у `FETCH_REF`.
 */
const MAIN = 'main';

/**
 * Куда фетчим. Свой ref, а не `FETCH_HEAD`, и не `origin/main` — оба чужие.
 *
 * `origin/main` обновляется как ПОБОЧКА `git fetch <remote> <branch>`, и при нестандартном
 * refspec её может не случиться: слияние тогда повторило бы прошлое состояние и отчиталось
 * «обновлено». `FETCH_HEAD` не лучше: он общий на репозиторий, и человек (или его IDE),
 * успевший между нашими двумя командами фетчнуть свою ветку, подменил бы нам цель слияния —
 * раннер влил бы в main чужую ветку и назвал бы это обновлением фазы (ревью, 2-й проход).
 *
 * Ref под `refs/ralph/` не претендует ни на что человеческое: не ветка, в `git status` не
 * виден, в рабочем дереве его нет. Пишем его только мы, поэтому между fetch и merge он
 * измениться не может ни от чьих действий.
 */
const FETCH_REF = 'refs/ralph/consumer-main';

/**
 * Переменные, которыми окружение НАВЯЗЫВАЕТ git другой репозиторий. `git -C <root>` их не
 * перебивает: `GIT_DIR` сильнее ключа `-C`, и команда ушла бы в чужое дерево, а мы бы этого
 * не заметили — ff прошёл, лог зелёный, обновилось не то (ревью, 6-й проход).
 *
 * Взяться им есть откуда: раннер запускают из скрипта, из tmux, а то и из git-хука, который
 * выставляет их сам. Барьер живёт ЗДЕСЬ, а не в вызывающем: обещание «работаем в
 * consumerRoot» — часть контракта этой функции, и держать его на чистоте чужого окружения
 * значит не держать вовсе.
 */
export const GIT_CONTEXT_VARS = [
    'GIT_DIR',
    'GIT_WORK_TREE',
    'GIT_INDEX_FILE',
    'GIT_COMMON_DIR',
    'GIT_NAMESPACE',
    'GIT_OBJECT_DIRECTORY',
    'GIT_ALTERNATE_OBJECT_DIRECTORIES',
] as const;

/**
 * Окружение без навязанного репозитория. Остальное наследуется НАМЕРЕННО: `HOME`, конфиг
 * и credential-хелпер человека нужны, чтобы fetch вообще прошёл авторизацию у форжа.
 */
export function stripGitContext(env: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
    const out = { ...env };
    for (const key of GIT_CONTEXT_VARS) delete out[key];
    return out;
}

/**
 * `git -C <root> …` плюс два запрета, общих на ВСЕ команды этого модуля.
 *
 * `core.hooksPath` в никуда: `merge` запускает `post-merge` из конфигурации дерева ЧЕЛОВЕКА,
 * и хук получил бы полное окружение раннера — с токенами форжа и адресами (ревью, 6-й
 * проход). Хук там законный (его поставил себе человек), но исполнять его нашими руками и
 * нашим окружением мы не подряжались: обновление дерева — не то событие, ради которого
 * человек его писал.
 *
 * `submodule.recurse=false` — вторая половина запрета рекурсии в подмодуль продукта; сам
 * запрет разобран в шапке модуля. Оба ключа стоят на каждой команде намеренно: избирательно
 * — значит однажды забыть на новой.
 */
function gitIn(root: string, args: string[]): string[] {
    return ['-C', root, '-c', 'core.hooksPath=/dev/null', '-c', 'submodule.recurse=false', ...args];
}

/**
 * Подтянуть дерево потребителя до `origin/main` после мерджа фазы.
 *
 * Best-effort по определению: следующая фаза строится в дереве РАБОТЫ, и состояние дерева
 * человека её не блокирует. Поэтому здесь нет ни одного пути, который бросает или
 * останавливает петлю, — только исход и строка в логе.
 */
export function updateConsumerTree(
    roots: TResolvedRoots | null,
    { runArgvFn, logFn, env }: TConsumerTreeDeps,
): TConsumerTreeKind {
    // Одно окружение на все команды: собирается один раз, чтобы «забыть прокинуть» было
    // негде. `undefined` означает «вызывающий окружением не распоряжается» — тогда и мы не.
    const gitEnv = env === undefined ? undefined : { env: stripGitContext(env) };
    const git = (args: string[]): string => runArgvFn('git', gitIn(consumerRoot, args), gitEnv);
    // Сетевой вызов здесь один — fetch, и он идёт с запретом промпта кредов (задача 71) и
    // сроком (задача 30): без кредов git ждёт логина на tty, без срока молчащий origin держит
    // вызов вечно — и AFK-раннер висел бы в пост-мердж обновлении.
    const gitNet = (args: string[]): string =>
        runArgvFn(
            'git',
            gitIn(consumerRoot, args),
            gitNetworkOpts(env === undefined ? undefined : stripGitContext(env)),
        );
    // Раскладки нет — нет и понятия «дерево потребителя»: пути скриптов в этой раскладке
    // относительны дереву работы, и обновлять нечего. Молча: сообщать не о чем.
    if (!roots) return 'no-roots';
    const { consumerRoot, executionRoot } = roots;
    // Дерево потребителя и есть дерево работы: раннер сам держит его на свежем origin/main
    // (detach после мерджа), второе обновление было бы холостым.
    if (consumerRoot === executionRoot) return 'same-tree';

    // Грязь считаем по ОТСЛЕЖИВАЕМЫМ файлам. `runtimeDir` по умолчанию лежит под
    // `consumerRoot` и не версионируется вовсе — с учётом untracked дерево было бы грязным
    // всегда, то есть обновление не случалось бы ни разу в той самой раскладке, ради
    // которой оно написано. Untracked-файл, который слияние затопчет, всё равно не пройдёт:
    // `merge --ff-only` откажется сам и скажет, чем именно — но только если слияние обязано
    // его перезаписать: правку в соседнем файле git не заметит (ревью, 6-й проход).
    // `null` — «не знаю»: git промолчать не может, поэтому отказ команды это НЕ «чисто»
    // (то же fail-closed, что у `ensureClean` для дерева работы). Спрашивается дважды —
    // здесь и вплотную к слиянию, — поэтому вынесено функцией.
    const dirtyNow = (): string | null => {
        try {
            return git(['status', '--porcelain', '--untracked-files=no']);
        } catch (e) {
            logFn(
                `⚠ Дерево потребителя ${consumerRoot}: git status не отработал (${(e as Error).message}) — ` +
                    `не трогаю. Смердженная фаза приедет туда твоим \`git pull --ff-only\`.`,
            );
            return null;
        }
    };
    const dirty = dirtyNow();
    if (dirty === null) return 'failed';
    if (dirty) {
        logFn(
            `⚠ Дерево потребителя ${consumerRoot} грязное — не трогаю: разбирать твои правки ` +
                `раннеру нечем. Смердженная фаза приедет туда после \`git pull --ff-only\`; ` +
                `до этого скрипты потребителя останутся прежней версии.\n${dirty}`,
        );
        return 'dirty';
    }

    // На какой ветке стоит дерево человека. `symbolic-ref` отказом отвечает на detached
    // HEAD — это не сбой, а тот же ответ «не наша ветка», только другим каналом.
    const branchNow = (): string => {
        try {
            return git(['symbolic-ref', '--quiet', '--short', 'HEAD']).trim();
        } catch {
            return '';
        }
    };
    const offMain = (branch: string): TConsumerTreeKind => {
        logFn(
            `⚠ Дерево потребителя ${consumerRoot} не на ${MAIN} ` +
                `(${branch || 'detached HEAD'}) — не трогаю: переключать ветку человека раннер ` +
                `не станет. Вернёшься на ${MAIN} — \`git pull --ff-only\` подтянет смердженную фазу.`,
        );
        return 'off-main';
    };
    const branch = branchNow();
    if (branch !== MAIN) return offMain(branch);

    // Снимок HEAD — для диагностики: если после слияния дерево окажется не там, где мы его
    // оставили, человеку нужно знать, от чего оно ушло.
    const headSha = (): string => {
        try {
            return git(['rev-parse', 'HEAD']).trim();
        } catch {
            return '';
        }
    };

    // Всё, что ниже, живёт в ОДНОМ `try/finally`: ref создаётся первой же командой, и любой
    // ранний выход после неё оставил бы его в чужом репозитории (ревью, 4-й проход).
    let target = '';
    try {
        try {
            // `--no-recurse-submodules` — не гигиена, а исполнение обещания в шапке модуля:
            // ДЕФОЛТ `fetch.recurseSubmodules` — `on-demand`, то есть fetch, принёсший новый
            // gitlink продукта, сам зашёл бы в его репозиторий и дописал туда объекты и refs.
            // Ровно в тот каталог, который мы объявили неприкосновенным (ревью, 1-й проход).
            // `-c submodule.recurse=false` закрывает вторую половину: потребитель мог
            // включить рекурсию в своём конфиге, и тогда в подмодуль полез бы ещё и merge.
            //
            // `--no-write-fetch-head` — про чужое: `FETCH_HEAD` один на репозиторий, и наш
            // fetch затирал бы то, что человек только что нафетчил себе. Его последующий
            // `git merge FETCH_HEAD` слил бы НАШУ цель вместо своей (ревью, 4-й проход).
            gitNet([
                'fetch',
                '--no-recurse-submodules',
                '--no-write-fetch-head',
                'origin',
                // `+` — принудительное обновление СВОЕГО ref'а: перемотка ветки на
                // origin (rebase, force-push) не должна оставлять раннера с отказом.
                `+refs/heads/${MAIN}:${FETCH_REF}`,
            ]);
            // Дальше работаем ЗАФИКСИРОВАННЫМ sha, а не именем ref'а: имя пришлось бы
            // разрешать ещё раз в момент слияния, а между этими моментами ref может
            // обновить соседний экземпляр раннера того же потребителя.
            target = git(['rev-parse', '--verify', `${FETCH_REF}^{commit}`]).trim();
        } catch (e) {
            logFn(
                `⚠ Дерево потребителя ${consumerRoot} не обновилось: не удалось получить ` +
                    `origin/${MAIN} (${(e as Error).message}). Разбери руками: ` +
                    `\`git -C ${consumerRoot} pull --ff-only\`.`,
            );
            return 'failed';
        }
        // Ответ коллаборатора проверяем ФОРМОЙ, а не доверием: `runArgvFn` инжектируется, и
        // контракт «вернёт полный object id» держится только на боевой реализации. Слияние
        // по неразобранной строке ушло бы куда угодно, включая `HEAD~1` (ревью, 4-й проход).
        // 40 hex — SHA-1, 64 — SHA-256: у git есть оба формата хранилища, и требовать
        // первый значило бы отказывать репозиторию второго навсегда (ревью, 5-й проход).
        if (!/^([0-9a-f]{40}|[0-9a-f]{64})$/.test(target)) {
            logFn(
                `⚠ Дерево потребителя ${consumerRoot} не обновилось: на месте sha пришло ` +
                    `«${target}» — сливать по этому нельзя. Разбери руками: ` +
                    `\`git -C ${consumerRoot} pull --ff-only\`.`,
            );
            return 'failed';
        }

        // Между первыми проверками и слиянием у человека есть окно: он мог уйти на свою
        // ветку (тогда `merge --ff-only` перемотал бы ЕЁ) либо начать править файлы. Обе
        // сверки повторяются вплотную к команде — обещание «не трогаю грязное и чужую
        // ветку» иначе относилось бы к состоянию минутной давности (ревью, 5-й проход).
        const again = branchNow();
        if (again !== MAIN) return offMain(again);
        const dirtyAgain = dirtyNow();
        if (dirtyAgain === null || dirtyAgain !== '') {
            logFn(
                `⚠ Дерево потребителя ${consumerRoot} стало грязным, пока мы фетчили, — ` +
                    `не трогаю. Смердженная фаза приедет туда после \`git pull --ff-only\`.` +
                    (dirtyAgain ? `\n${dirtyAgain}` : ''),
            );
            return dirtyAgain === null ? 'failed' : 'dirty';
        }
        const was = headSha();
        try {
            // Сливаем зафиксированный sha. Только fast-forward: расхождение разбирает
            // человек, а не раннер. Отказ означает, что у него есть свои коммиты в main,
            // и мердж-коммит поверх них был бы произволом.
            git(['merge', '--ff-only', target]);
        } catch (e) {
            logFn(
                `⚠ Дерево потребителя ${consumerRoot} не обновилось (${(e as Error).message}). ` +
                    `Разбери руками: \`git -C ${consumerRoot} pull --ff-only\`. До этого скрипты ` +
                    `потребителя работают прежней версией.`,
            );
            return 'failed';
        }
        // Пост-сверка ловит ЧАСТЬ остатка того окна, и её честная цена названа в шапке
        // модуля: человек, успевший вернуться на `main` до этой строки, здесь не виден.
        // Поэтому строка — наблюдение с фактами, а не готовая команда отката: `reset --hard`,
        // выданный вслепую, откатил бы не ту ветку (ревью, 4-й проход).
        const after = branchNow();
        if (after !== MAIN) {
            logFn(
                `⛔ Дерево потребителя ${consumerRoot}: после слияния HEAD не на ${MAIN}, ` +
                    `а на «${after || 'detached HEAD'}» — ветку переключили прямо во время ` +
                    `обновления. До слияния было ${was || '(sha не прочитан)'}, слито ${target}. ` +
                    `Разберись руками: возможно, перемотана не та ветка.`,
            );
            return 'failed';
        }
        logFn(`✅ Дерево потребителя ${consumerRoot} обновлено до origin/${MAIN} (ff-only).`);
        return 'updated';
    } finally {
        // Ref за собой убираем ВСЕГДА. Оставленный, он держит старую историю GC-корнем в
        // репозитории ЧЕЛОВЕКА — тихо растущая цена за нашу служебную надобность.
        //
        // Удаляем сверкой со ЗНАЧЕНИЕМ (`update-ref -d <ref> <sha>`): имя ref'а одно на
        // потребителя, а экземпляров раннера у него может быть несколько (prod и playground
        // на одном дереве). Без сверки мы удалили бы чужой, только что записанный ref.
        // Имя при этом намеренно не уникализируется: оба экземпляра фетчат один и тот же
        // `origin/main`, то есть пишут в ref одно и то же значение, и разойтись он может
        // только при гонке с продвижением ветки — там сверка и сработает, оставив ref
        // владельцу (ревью, 4-й проход).
        // Без зафиксированного sha ref не удаляем ВОВСЕ: fetch мог не дойти до записи, и
        // тогда по этому имени лежит ref соседнего экземпляра — удалять чужое, не имея чем
        // подтвердить владение, хуже, чем оставить своё (ревью, 5-й проход).
        if (target)
            try {
                git(['update-ref', '-d', FETCH_REF, target]);
            } catch (e) {
                // Не убрался — исход обновления это не меняет (мусор, а не отказ), но молчать
                // нельзя: GC-корень в чужом репозитории обязан быть назван вместе с адресом.
                logFn(
                    `⚠ Не убрал служебный ref ${FETCH_REF} в ${consumerRoot} ` +
                        `(${(e as Error).message}). Если он не принадлежит соседнему экземпляру — ` +
                        `убери: \`git -C ${consumerRoot} update-ref -d ${FETCH_REF}\`.`,
                );
            }
    }
}
