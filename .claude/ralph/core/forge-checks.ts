// Чек PR НА СТОРОНЕ ФОРЖА: ожидание вердикта и классификация красного (#269).
//
// Зачем модуль появился. Локальный гейт (`core/gate.ts`) гоняет чеки в дереве раннера и
// мерджит, когда все зелёные. У площадки при этом СВОЙ чек — прогон CI на воркере, — и
// мердж она отвергает (400), пока он красный. Раннер этого вердикта не читал вовсе: три
// попытки мерджа через 30 с и стоп «PR оставлен человеку». 05.09.2026 петля так вставала
// дважды за вечер, и оба раза причина была видна ТОЛЬКО в контейнере площадки, а на хосте
// не воспроизводилась: OOM контейнера гейта (#268, прогон 350) и подмена пути `/repo`
// внутри URL оснасткой теста (прогоны 355/356). Ночью в окне 15–29.09 такой стоп стоит
// часов простоя петли.
//
// Что здесь есть и чего здесь нет. Здесь — ПОЛИТИКА ядра: сколько ждать, что считать
// вердиктом, и главное — «этот отказ чинится кодом» против «этот зовёт человека». Разбор
// ответов площадки (какие поля, какие статусы, где лежит лог куба) живёт в адаптере:
// ядро форжа не знает и знать не должно (`tests/core-purity.test.ts`).
//
// Типы шва здесь ОБЪЯВЛЕНЫ, а не импортированы из `adapters/adapters.ts`, — тем же
// приёмом, что `GateEnv` в gate.ts: ядро зависит от формы, а не от модуля контрактов.
// Формы совпадают структурно, и это проверяет контрактный сьют.
//
// #278: вердикт форжа не нёс адреса головы PR, к которой относится прогон, — только
// `created_at` прогона. Раньше это спасал только тайминг (локальный гейт занимает
// 6–10,5 мин, за это время форж обычно успевает завести новый прогон), а не механизм:
// худший случай — стухший `forge-env` (OOM) от прогона ДО пуша правок останавливал фазу
// человеку по логу, который уже не про эту голову. `sinceMs` в `WaitForForgeChecksDeps`
// закрывает это той же идеей, что `healedRunId`, но шире: прогон с `createdAt` раньше
// пуша не годится в вердикт вообще, зелёный он или красный.
import { errorText } from '../shared/ralph-util.ts';

// Состояние чека форжа, приведённое к четырём значениям. Сырой статус площадки при этом
// не теряется (`rawStatus`) — он нужен в тексте отказа: «ждали 20 минут, а он всё
// awaiting_approval» чинится не тем же, чем «всё processing».
export type ForgeCheckState = 'success' | 'failed' | 'pending' | 'none';

export type ForgeCheckRun = {
    // Имя workflow у форжа (`gate`) — им же адресуется прогон при чтении лога.
    workflow: string;
    // Идентификатор прогона в терминах форжа (у площадки это строковый счётчик, «356»).
    runId: string;
    state: ForgeCheckState;
    rawStatus: string;
    // #278: момент старта прогона (epoch ms). Отсутствует, если адаптер не смог разобрать
    // дату площадки, — тогда свежесть этого прогона не проверяется вовсе (см. `isStale`
    // ниже): «дата не разобралась» не повод объявлять вердикт устаревшим, это отдельный
    // сбой формы ответа.
    createdAt?: number;
};

// `state` — свёртка по всем прогонам: любой красный красит целое, иначе любой ждущий
// оставляет целое ждущим. Свёртку делает АДАПТЕР (он знает словарь статусов), ядро
// принимает готовую: иначе правило «canceled — это красный» пришлось бы держать в двух
// местах и оно бы разъехалось.
export type ForgeChecks = { state: ForgeCheckState; runs: ForgeCheckRun[] };

// Диагноз красного чека: какой куб упал и хвост его лога (уже без ANSI, уже обрезанный).
export type ForgeCheckFailure = {
    workflow: string;
    runId: string;
    cube: string;
    log: string;
};

export type ForgeWaitOutcome =
    | { kind: 'green' }
    // Чеков у PR нет вовсе — форж их не заводит (репозиторий без CI). Приговор выносит
    // политика гейта (задача 81): при `optional` мердж идёт, площадке нечего отвергать, при
    // `required` — стоп. Прогон в очереди сюда не попадает: площадка отдаёт его ждущим
    // (`created`), а не `none` — так по логу петли потребителя.
    | { kind: 'absent' }
    | { kind: 'red'; run: ForgeCheckRun }
    | { kind: 'timeout'; detail: string }
    | { kind: 'error'; detail: string };

// Умолчания. Потолок ожидания — 20 минут: полный гейт на воркере VPS занимает 6–10,5 мин
// (замер 04.09, `docs/deploy/research.md`), и двойной запас закрывает очередь воркера при
// `max_slots: 1`. Опрос раз в 30 с: чаще — лишние запросы к площадке, реже — до получаса
// на ровном месте, если чек позеленел сразу после круга.
//
// Число НЕ связано с `deadman.gateSilenceMs` и связывать его незачем (правка по ревью
// #269). Прежняя редакция обещала равенство этих двух порогов, но держать его было
// нечем — `tryMergePhase` даже не прокидывает сюда `timeoutMs`, — а главное, само
// равенство ничего не значит: цикл пишет строку каждые 30 с, то есть тишины, которой
// управляет deadman, здесь не возникает вовсе. Порог deadman'а вправе вернуться к десяти
// минутам независимо от этого потолка.
const DEFAULT_TIMEOUT_MS = 20 * 60 * 1000;
const DEFAULT_POLL_MS = 30 * 1000;
// Отдельный, КОРОТКИЙ бюджет на «чека ещё нет». Чек привязан к событию `pr_update`, и
// после пуша прогон появляется не мгновенно. Но репозиторий вовсе без CI отвечает так же
// — и платить за него полным потолком значило бы добавить 20 минут к каждому мерджу.
const DEFAULT_ABSENT_GRACE_MS = 2 * 60 * 1000;
// Сбой чтения — сгоревшая попытка, а не вердикт (тот же приём, что у mergeConfirmed в
// gate.ts). Но устойчивый сбой обязан кончиться отказом, а не 20 минутами тишины.
const DEFAULT_MAX_READ_ERRORS = 3;

export type WaitForForgeChecksDeps = {
    // Чтение чека у форжа. Fail-closed по контракту шва: не смогли — бросает.
    readFn: () => ForgeChecks;
    sleepFn: (ms: number) => void;
    nowFn: () => number;
    logFn: (msg: string) => void;
    timeoutMs?: number;
    pollMs?: number;
    absentGraceMs?: number;
    maxReadErrors?: number;
    // Прогон, по логу которого чини-сессия УЖЕ отработала (правка по ревью #269).
    // Форж отдаёт ПОСЛЕДНИЙ прогон каждого workflow, а не прогон конкретного sha, — то
    // есть после пуша правок какое-то время он честно отвечает вердиктом ПРЕДЫДУЩЕГО
    // прогона. Без этого поля петля читала такой красный как свежий и тратила вторую
    // (последнюю) попытку `gateHealAttempts` на лог, который уже починен, — а исчерпав
    // бюджет, вставала. Совпал номер — вердикт ещё не обновился: ждём, а не лечим.
    healedRunId?: string;
    // #278: момент пуша правок, epoch ms (у `core/gate.ts` — время коммита головы PR).
    // Тот же грабль, что у `healedRunId`, но ШИРЕ: форж отдаёт ПОСЛЕДНИЙ прогон workflow
    // независимо от того, лечили мы его или нет, — прогон, у которого `createdAt` РАНЬШЕ
    // этого момента, отвечает на вопрос про ЧУЖУЮ, более раннюю голову PR и не может ни
    // зазеленить, ни покрасить мердж текущей. Без этого поля первый же красный отказ
    // СРЕДЫ (`forge-env`), доставшийся от прогона, который форж ещё не сменил, читался
    // как актуальный и останавливал фазу человеку по логу, который уже не про эту голову.
    // Не задан ⇒ свежесть не проверяется вовсе — прежнее поведение.
    sinceMs?: number;
    // Задача 81: политика `required` внешнего CI. Прогон без `createdAt` в вердикте
    // (зелёном или красном) тогда — `error`, а не «считаем свежим»: свежесть такого
    // прогона не проверить, а для `required` «не смогли проверить» мердж не даёт. Ждать
    // дальше бессмысленно — дата, не разобравшаяся в одном ответе, не разберётся и в
    // следующем. Ждущий прогон без даты вердиктом не является и ожидание не обрывает.
    requireDated?: boolean;
};

// Допуск на расхождение часов (правка по ревью #278). `sinceMs` снимается ЛОКАЛЬНО
// (`git log -1 --format=%cI` на VPS), а `run.createdAt` ставит СЕРВЕР площадки — это две
// разные машины и двое часов. Строгое сравнение без запаса означало бы, что ушедшие
// вперёд на минуту часы VPS (дрейф NTP после ребута — на этой машине ребуты уже были)
// делают устаревшим КАЖДЫЙ честно свежий прогон: поллинг крутится все 20 минут, отдаёт
// `timeout`, и механизм, заведённый против ночных стопов петли, начинает их производить.
// Цена запаса — интервал «коммит → пуш → форж завёл прогон», то есть секунды-десятки
// секунд: две минуты его не съедают, а дрейф часов закрывают.
const STALE_TOLERANCE_MS = 2 * 60 * 1000;

// Прогон старше пуша правок — вердикт другого, более раннего состояния кода (#278).
// `createdAt` не задан (адаптер не смог разобрать дату площадки) ⇒ прогон считается
// свежим: сбой формы ответа — отдельная причина отказа, а не повод объявить вердикт
// устаревшим. Эту причину отказа называет `requireDated` (задача 81): при политике
// `required` до `isStale` прогон без даты не доходит вовсе.
function isStale(run: ForgeCheckRun, sinceMs: number | undefined): boolean {
    return (
        sinceMs !== undefined &&
        run.createdAt !== undefined &&
        run.createdAt < sinceMs - STALE_TOLERANCE_MS
    );
}

// Прогон формально старше границы, но внутри допуска — принят как свежий. Одиночный
// случай штатен (границу двигают секунды между коммитом и стартом прогона), а вот
// повторяющийся — признак разъехавшихся часов VPS и площадки. Без строки в логе такой
// дрейф выглядел бы как молчаливое ожидание, поэтому он именуется вслух.
function clockSkewMs(run: ForgeCheckRun, sinceMs: number | undefined): number | undefined {
    if (sinceMs === undefined || run.createdAt === undefined) return undefined;
    const behind = sinceMs - run.createdAt;

    return behind > 0 && behind <= STALE_TOLERANCE_MS ? behind : undefined;
}

/**
 * Ждать вердикта чека PR у форжа. Возвращает исход, решение принимает вызывающий.
 *
 * Время — параметрами (`nowFn`/`sleepFn`), а не `Date.now()` в теле: тест на потолок
 * иначе недетерминирован и идёт двадцать реальных минут.
 *
 * Лог пишется НА КАЖДОМ круге, и это не многословие: свежесть `ralph.log` — единственный
 * признак жизни петли для deadman'а, а молчать все двадцать минут потолка значило бы
 * перешагнуть любой разумный порог тишины (`deadman.gateSilenceMs` — 20 мин сегодня,
 * 10 мин в прежней редакции) и получить ночью ложный DEADMAN-пуш. Строка на круг
 * снимает вопрос при ЛЮБОМ пороге, а не при сегодняшнем. Маркер `🚦` выбран нарочно:
 * он держит режим deadman'а в `gate`
 * (`GATE_RE` в `runtime/deadman.ts`), а нейтральная строка уронила бы его в `default`
 * с пятиминутным порогом.
 */
export function waitForForgeChecks({
    readFn,
    sleepFn,
    nowFn,
    logFn,
    timeoutMs = DEFAULT_TIMEOUT_MS,
    pollMs = DEFAULT_POLL_MS,
    absentGraceMs = DEFAULT_ABSENT_GRACE_MS,
    maxReadErrors = DEFAULT_MAX_READ_ERRORS,
    healedRunId = '',
    sinceMs,
    requireDated = false,
}: WaitForForgeChecksDeps): ForgeWaitOutcome {
    const started = nowFn();
    let readErrors = 0;
    let lastRaw = '';
    for (;;) {
        const elapsed = nowFn() - started;
        let checks: ForgeChecks;
        try {
            checks = readFn();
            readErrors = 0;
        } catch (e: unknown) {
            readErrors += 1;
            const why = errorText(e);
            logFn(
                `🚦 Чек площадки: чтение не удалось (${String(readErrors)}/${String(maxReadErrors)}) — ${why}`,
            );
            if (readErrors >= maxReadErrors) {
                return { kind: 'error', detail: why };
            }
            sleepFn(pollMs);
            continue;
        }
        lastRaw = checks.runs.map((r) => `${r.workflow}=${r.rawStatus}`).join(', ') || checks.state;
        if (requireDated && (checks.state === 'success' || checks.state === 'failed')) {
            if (checks.runs.length === 0) {
                return {
                    kind: 'error',
                    detail: `форж вернул ${checks.state} без единого прогона — политика required подтверждать нечем`,
                };
            }
            const undated = checks.runs.find((r) => r.createdAt === undefined);
            if (undated) {
                return {
                    kind: 'error',
                    detail:
                        `прогон ${undated.runId} (${undated.workflow}=${undated.rawStatus}) без даты — ` +
                        'свежесть не проверить, политика required мердж не даёт',
                };
            }
        }
        for (const run of checks.runs) {
            const skew = clockSkewMs(run, sinceMs);
            if (skew !== undefined) {
                logFn(
                    `🚦 Чек площадки: прогон ${run.runId} старше пуша правок на ${String(Math.round(skew / 1000))}с — ` +
                        `это внутри допуска (${String(Math.round(STALE_TOLERANCE_MS / 1000))}с), принят как свежий. ` +
                        'Повторяется — сверить часы VPS с часами площадки.',
                );
            }
        }
        if (checks.state === 'failed') {
            const failedRuns = checks.runs.filter((r) => r.state === 'failed');
            if (failedRuns.length === 0) {
                // Свёртка сказала «красный», а красного прогона в списке нет — форж ответил
                // не по контракту шва. Мерджить на этом нельзя, и «подожду ещё» тоже неправда.
                return { kind: 'error', detail: 'форж вернул failed без единого упавшего прогона' };
            }
            // Кандидат в вердикт — упавший прогон, который НЕ уже пролечен (healedRunId)
            // И НЕ старше пуша правок (sinceMs, #278): оба признака об одном и том же —
            // этот вердикт ещё не про голову, которую мы просим форж проверить.
            //
            // Из подходящих сначала берётся ЛЮБОЙ, а не первый в списке: workflow может
            // быть несколько, и «первым красным» вполне окажется отфильтрованный, а
            // вторым — НОВЫЙ красный прогон соседнего workflow (правка по ревью #269).
            //
            // `healedRunId === ''` — умолчание «лечения не было», а не номер прогона:
            // без этой оговорки красный прогон с пустым `runId` (чужая реализация шва
            // вправе его отдать — ядро объявляет тип само) переставал быть кандидатом,
            // и вердикт превращался в 20 минут ожидания «нового прогона» (правка по ревью).
            const red = failedRuns.find(
                (r) => (healedRunId === '' || r.runId !== healedRunId) && !isStale(r, sinceMs),
            );
            if (red) {
                logFn(`🚦 Чек площадки КРАСНЫЙ: workflow ${red.workflow}, прогон ${red.runId}.`);
                return { kind: 'red', run: red };
            }
            // Ни один упавший прогон не годится в вердикт: каждый либо уже пролечен, либо
            // старше пуша правок — новый ещё не завёлся. Ждём его, а не тратим попытку
            // лечения и не стопаемся на диагнозе, который уже не про эту голову.
            const stuck =
                (healedRunId === ''
                    ? undefined
                    : failedRuns.find((r) => r.runId === healedRunId)) ?? failedRuns[0];
            // Причина ожидания: «этот прогон мы уже лечили» против «этот прогон старше
            // пуша правок». Имя — про вторую ветку прямо: `staleOnly` читалось как
            // «только устаревшие» (правка по ревью).
            const waitingForNewerRun = healedRunId === '' || stuck.runId !== healedRunId;
            if (elapsed >= timeoutMs) {
                return {
                    kind: 'timeout',
                    detail: waitingForNewerRun
                        ? `за ${String(Math.round(timeoutMs / 60000))} мин форж не завёл прогон новее пуша ` +
                          `правок (последний известный ${stuck.runId} старше него), последнее состояние: ${lastRaw}`
                        : `за ${String(Math.round(timeoutMs / 60000))} мин форж не завёл прогон новее ` +
                          `${healedRunId} (по нему чини-сессия уже отработала), последнее состояние: ${lastRaw}`,
                };
            }
            logFn(
                waitingForNewerRun
                    ? `🚦 Чек площадки показывает прогон ${stuck.runId} старше пуша правок — жду новый ` +
                          `(прошло ${String(Math.round(elapsed / 1000))}с).`
                    : `🚦 Чек площадки всё ещё показывает прогон ${stuck.runId} — по нему уже лечили, ` +
                          `жду новый (прошло ${String(Math.round(elapsed / 1000))}с).`,
            );
            sleepFn(pollMs);
            continue;
        }
        if (checks.state === 'success') {
            // #278: тот же грабль, что у красного, — форж вправе отдать ЗЕЛЁНЫЙ вердикт
            // прогона, который стартовал ДО пуша правок. Смерджить на нём значило бы не
            // проверить площадкой именно ту голову, которую мы просим её проверить.
            // `some`, а не `every` (правка по ревью): годность оценивается у КАЖДОГО
            // прогона отдельно — ровно как в красной ветке выше. С `every` достаточно было
            // одного свежего прогона СОСЕДНЕГО workflow, чтобы принять зелёный вердикт,
            // в котором сам `gate` — старый, то есть ровно та дыра, которую закрывает #278.
            const stale = checks.runs.some((r) => isStale(r, sinceMs));
            if (stale) {
                if (elapsed >= timeoutMs) {
                    return {
                        kind: 'timeout',
                        detail:
                            `за ${String(Math.round(timeoutMs / 60000))} мин форж не завёл прогон новее пуша ` +
                            `правок, последнее состояние: ${lastRaw}`,
                    };
                }
                logFn(
                    `🚦 Чек площадки зелёный, но старше пуша правок (${lastRaw}) — жду новый прогон ` +
                        `(прошло ${String(Math.round(elapsed / 1000))}с).`,
                );
                sleepFn(pollMs);
                continue;
            }
            logFn(`🚦 Чек площадки зелёный (${lastRaw}) — мердж разрешён.`);
            return { kind: 'green' };
        }
        if (checks.state === 'none' && elapsed >= absentGraceMs) {
            logFn(
                `🚦 Чек площадки: за ${String(Math.round(absentGraceMs / 1000))}с ни одного прогона не завелось — ` +
                    'мердж решает политика внешнего CI (gate.externalCi).',
            );
            return { kind: 'absent' };
        }
        if (elapsed >= timeoutMs) {
            return {
                kind: 'timeout',
                detail: `за ${String(Math.round(timeoutMs / 60000))} мин чек не сошёлся, последнее состояние: ${lastRaw}`,
            };
        }
        logFn(`🚦 Чек площадки ждёт (${lastRaw}), прошло ${String(Math.round(elapsed / 1000))}с.`);
        sleepFn(pollMs);
    }
}

// ── Классификация красного: чинится кодом или зовёт человека ─────────────────

// Три исхода, а не два. `code` — работа для сессии лечения; `oom` и `aborted` — стоп
// человеку, но с РАЗНЫМ диагнозом, и схлопывать их нельзя: первый чинят памятью
// контейнера, второй — вообще ничем (прогон отменили или он упёрся в свой потолок).
export type ForgeFailureKind = 'oom' | 'aborted' | 'code';

// Сигнатуры ОТКАЗА СРЕДЫ, а не кода. Контейнер гейта убит по памяти — vitest теряет форк
// и печатает «Worker exited unexpectedly»; docker отдаёт 137; ядро пишет про cgroup.
const ENV_FAILURE_RE =
    /Worker exited unexpectedly|Worker forks emitted error|\bexit code 137\b|\b137\b\s*\(SIGKILL\)|out of memory|Out of memory|OOMKilled|Killed process/;

// Проваленные КЕЙСЫ. Их наличие — приговор в пользу кода: если тесты честно упали, чинить
// надо их, каким бы шумом ни сопровождался прогон. Формы взяты из реальных логов куба
// `test` (vitest печатает обе строки сводки) плюс общая `FAIL <файл>` на случай другого
// раннера в кубе.
const FAILED_CASES_RE = /(?:Test Files|Tests)\s+\d+\s+failed|^\s*FAIL\s+\S/m;

// Статусы прогона, которые означают «его прервали», а не «он нашёл дефект». Рестарт
// воркера посреди задания — штатное действие дежурного (`RUNBOOK.md`, «Рестарт воркера
// только на пустом»), и прогон при этом приходит `canceled` с обрывком лога первого же
// куба. Лечить такое кодом значит потратить весь бюджет `gateHealAttempts` на починку
// того, что никто не ломал. Правка по ревью.
const ABORTED_STATUSES = new Set(['canceled', 'timeout', 'rejected']);

/**
 * Чинится ли красный чек площадки кодом.
 *
 * `aborted` — прогон прерван (отмена, потолок времени, отказ площадки). В логе при этом
 * лежит обрывок случайного куба, и код тут ни при чём.
 *
 * `oom` — отказ СРЕДЫ (память контейнера гейта, убитый форк): сессия лечения по такому
 * логу начнёт «чинить» здоровые тесты, потому что ей покажут падение, которого в коде
 * нет. Это стоп человеку с диагнозом, а не работа для модели.
 *
 * `code` — всё остальное, включая случай «есть и сигнатура среды, и проваленные кейсы»:
 * упавший кейс сильнее, чем шумный воркер. Пустой лог тоже `code` — «диагноз среды»
 * без единого свидетельства увёл бы к человеку отказ, который правится кодом.
 *
 * Сырой статус прогона — второй аргумент, а не поле лога: отмену видно ТОЛЬКО по нему,
 * в тексте лога она неотличима от обрыва по любой другой причине.
 */
export function classifyForgeFailure(log: string, rawStatus = ''): ForgeFailureKind {
    if (ABORTED_STATUSES.has(rawStatus)) return 'aborted';
    if (!ENV_FAILURE_RE.test(log)) return 'code';
    return FAILED_CASES_RE.test(log) ? 'code' : 'oom';
}
