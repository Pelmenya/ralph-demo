// Интерфейсы адаптеров ralph — контракты точек расширения фреймворка (#262, фаза 5).
//
// Зачем. Ядро петли (issue → код → PR → ревью → гейт → мердж) переносимо между
// проектами; проектно-специфичное ПОВЕДЕНИЕ (иной форж, иной стек сборки, иной
// механизм деплоя, иной нотификатор, иной агент-рантайм) — нет. #204 сняло
// проектные ЗНАЧЕНИЯ в `ralph.config.json`; этот файл описывает ИНТЕРФЕЙСЫ для
// того, что значением-в-конфиге не закрыть. Пять швов — ровно из плана фазы
// (`docs/ralph-mini-framework/plan.md`, фаза 5) и кандидатов PRD (§«Кандидаты в
// адаптеры»): источник задач (форж), гейт, нотификатор, деплой-проверка, рантайм
// кодер-сессии.
//
// Что это и что НЕ это. Здесь — ТОЛЬКО контракты (типы и сигнатуры), которым в
// фазе 5 подчинят текущие реализации (#369) и против которых напишут контрактный
// сьют (#370). Реализаций тут нет.
//
// Инварианты в контракте. Тип не выражает «бросает» vs «глотает», поэтому режим
// отказа каждого метода зафиксирован в докстроке — это часть контракта, не деталь:
//   • Fail-closed (метод БРОСАЕТ при сбое) — всё, что решает, что́ брать в работу и
//     что мерджить: чтение очереди issues, резолв sha мерджа, прогон чеков. Тихий
//     дефолт здесь — худший исход (инвариант №1 в `.claude/ralph/CLAUDE.md`).
//   • Fail-open (метод НЕ бросает, сигналит возвратом/логом) — косметика, чей сбой
//     не должен ронять петлю: доставка пуша, метки, закрытие milestone, синк доски.
//
// Форма. Erasable-only TypeScript без билд-шага (нативный type stripping Node ≥24):
// только `type`-алиасы и аннотации — ни `enum`, ни namespace-рантайма, ни parameter
// properties; в рантайме от файла не остаётся ничего. Стиль ядра — `type` без
// префикса `T` (как `Issue`/`Phase`/`GateEnv`/`DeployOutcome` в соседних модулях),
// не app-конвенция `TName`. Модуль САМОДОСТАТОЧЕН: не импортирует боевые модули
// ядра — контракт есть абстракция, которой они подчиняются, а не наоборот (иначе
// зависимость поехала бы «абстракция → реализация»). Формы совпадают с боевыми
// структурно; #369 сведёт их в один источник.

// ---------------------------------------------------------------------------------
// Общие типы данных швов
// ---------------------------------------------------------------------------------

// Issue в форме, которую читает петля для ОЧЕРЕДИ (`gh issue list --json number,title,
// labels,author`). Тела здесь нет намеренно: очередь — это список, и тянуть тела всех
// карточек ради выбора первой значило бы платить за то, что не используется. Тело
// отдельной карточки читается своим методом (`getIssue`, #50).
export type Issue = {
    number: number;
    title: string;
    labels?: Array<{ name: string }>;
    author?: { login?: string };
    // #18: когда карточка заведена, в ISO. Нужен сроку годности карточек лестницы —
    // возраст читается из форжа и не требует от раннера собственной памяти о том, в какой
    // фазе карточка родилась. Необязательное: реализация, которая даты не отдаёт, просто
    // выключает чистку, а не ломает очередь.
    createdAt?: string;
};

// PR в форме, которую читает петля (`gh pr list --json number,labels`). `labels`
// нужны гейту для проверки `hold`/`blocked`.
export type PullRequest = {
    number: number;
    labels?: Array<{ name: string }>;
};

// Фаза = milestone (очередь задач) + ветка (`feature/…`). State адресует фазу по
// ИМЕНИ milestone, не по индексу (инвариант M7).
export type Phase = { milestone: string; branch: string };

// Комментарий PR в форме, которую читает счёт находок ревью (#168/#169). Форж держит
// ревью на разных поверхностях (у GitHub их три: тред issue, inline-комментарии ревью и
// сводное тело прохода; у SourceCraft одна лента), и раскладка по ним — знание форжа.
// Наружу шов отдаёт то, от чего зависит счёт, и ничего больше:
//   • `body` — текст; метку severity из него разбирает считалка, не адаптер;
//   • `isSummary` — сводный обзорный комментарий прохода ревью. По контракту промпта он
//     размечен меткой severity, но ДУБЛИРУЕТ находки inline-комментариев того же прохода,
//     поэтому в счёте идёт в unmarked: иначе каждый проход давал бы систематический +1;
//   • `author` — логин/slug автора. Репозиторий публичный, и любой прохожий, оставивший
//     «🔴 [blocker] lol», иначе завысил бы метрику: считаются только доверенные авторы.
export type ReviewComment = {
    body: string;
    isSummary: boolean;
    author?: string;
};

// Куда именно в диффе смотрит комментарий ревью (#45). Якорь НЕ косметика: у площадки
// именно его отсутствие отличает сводку прохода от находки (см. ReviewComment.isSummary),
// то есть комментарий без якоря уедет в unmarked и в счёт находок не попадёт. Строка —
// 1-based номер в файле; форж-специфика (у GitHub нужен ещё sha головы, у SourceCraft —
// сторона диффа) остаётся внутри реализации.
// `side` (#41): сторона диффа. Удалённая строка есть только в старой версии файла, и
// замечание к ней с прошитой новой стороной легло бы на чужую строку того же номера.
// Нет поля — новая сторона, как было до него.
export type ReviewCommentAnchor = { path: string; line: number; side?: 'LEFT' | 'RIGHT' };

// Место БЕЗ строки — файл целиком (#575). Средняя ступень отката между инлайном и
// сводкой: форж принимает якорь строки, только если строка входит в изменённый ХАНК,
// а самый ценный класс замечаний ревью — о ПРОПУЩЕННОМ («тут забыли погасить флаг»,
// «комментарий рядом протух после этого PR») — по природе своей целится в неизменённый
// код. Файл при этом в диффе есть, и место сохранимо: комментарий уровня файла.
//
// `line?: undefined` — не украшение, а дискриминант: без него `ReviewCommentAnchor`
// структурно подходил бы под файловый якорь, и реализация не смогла бы их развести.
export type ReviewCommentFileAnchor = { path: string; line?: undefined };

// Карточка целиком — то, что кодер-сессии нужно ПРОЧИТАТЬ, чтобы сделать работу (#50).
// Раньше читать её полагалось самой сессии («по номеру»); это было верно ровно до тех
// пор, пока у неё был CLI форжа. Теперь читает петля и кладёт в промпт как ДАННЫЕ.
//
// `open` (#43) — берётся ли карточка в работу по правилу очереди ПРЯМО СЕЙЧАС. Список
// очереди форж отдаёт с задержкой, и карточку, закрытую человеком между итерациями, он
// ещё держит открытой; точечное чтение одной карточки этой задержки не знает. Поле
// необязательное, и его отсутствие — «не знаю», а не «закрыта»: реализация без статуса
// возвращает прежнее поведение (лишнюю сессию), а не пустую очередь и сдачу фазы.
export type IssueDetails = { number: number; title: string; body: string; open?: boolean };

// Что петля просит поставить в PR от имени раннера. `anchor` необязателен: сводный
// комментарий прохода привязывать не к чему. Якорь без строки — комментарий уровня
// файла (#575), средняя ступень отката.
export type NewReviewComment = {
    body: string;
    anchor?: ReviewCommentAnchor | ReviewCommentFileAnchor;
};

// ── Чек PR на стороне форжа (#269) ────────────────────────────────────────────────
//
// Локальный гейт — не единственный, кто говорит «да» мерджу. У форжа есть СВОЙ чек
// (прогон CI), и мердж он отвергает, пока тот красный. Раннер этого вердикта не читал
// вовсе: три попытки мерджа через 30 с и стоп «PR оставлен человеку» — 05.09.2026 петля
// так встала дважды за вечер. Здесь описана та часть, без которой ожидание чека
// невыразимо: ЧТО у форжа спросить и ЧТО он ответит.

// Состояние чека, приведённое к четырём значениям. Сырой статус форжа при этом не
// теряется (`rawStatus`): «ждали 20 минут, а он всё awaiting_approval» и «всё processing»
// чинятся разным, и в тексте отказа человек обязан прочитать именно своё слово.
export type ForgeCheckState = 'success' | 'failed' | 'pending' | 'none';

// Один прогон CI. `runId`/`workflow` — адрес, по которому у форжа спрашивают детали
// красного (какой шаг упал и что в его логе).
export type ForgeCheckRun = {
    workflow: string;
    runId: string;
    state: ForgeCheckState;
    rawStatus: string;
    // #278: момент старта прогона (epoch ms), если реализация шва смогла его разобрать.
    // Ядро использует его, чтобы отличить вердикт ЭТОЙ головы PR от вердикта, оставшегося
    // с прогона до пуша правок (`core/forge-checks.ts`, `sinceMs`) — форж отдаёт ПОСЛЕДНИЙ
    // прогон workflow, а не прогон конкретного sha.
    createdAt?: number;
};

// Свёртку по прогонам делает РЕАЛИЗАЦИЯ, а не ядро: словарь статусов форж-специфичен
// (у одного «canceled» красный, у другого такого статуса нет вовсе), и держать это
// правило в двух местах значит однажды их разъединить.
export type ForgeChecks = { state: ForgeCheckState; runs: ForgeCheckRun[] };

// Диагноз красного чека: какой шаг прогона упал и хвост его лога — уже без управляющих
// символов и уже обрезанный. Обрезка и чистка — работа реализации: сотни килобайт лога
// с ANSI-вставками нельзя ни положить в промпт, ни искать в них сигнатуры отказа.
export type ForgeCheckFailure = {
    workflow: string;
    runId: string;
    cube: string;
    log: string;
};

// Заявка на PR фазы (#46). Целевая ветка не параметр: петля мерджит фазы только в `main`,
// и второй вариант тут означал бы не гибкость, а неопределённость — куда именно сдаётся
// фаза, решает не тот, кто заводит PR.
export type NewPullRequest = { branch: string; title: string; body: string };

// ---------------------------------------------------------------------------------
// 1. Источник задач (форж): issues, PR, мердж, метки, milestone, доска
// ---------------------------------------------------------------------------------
//
// Абстракция над форжем (сейчас — GitHub через `gh`; кандидаты — GitLab/Gitea).
// Создание PR ВХОДИТ в контракт с #46. Раньше не входило: его делегировали кодер-сессии
// (`claude -p`-сессия «создай PR»). Решение было верным ровно до тех пор, пока у сессии
// был CLI форжа; на площадке, где его нет, шаг оказался невыполнимым, а худший исход —
// не стоп, а отчёт «готово» без PR. Управление меткой `hold` тоже
// не в контракте: снять её может только человек (структурный барьер #222) — в
// адаптере намеренно нет такого метода.

export type TaskSourceAdapter = {
    // Форж доступен и токен принят? Зовётся из preflight, ДО первой работы.
    // Fail-closed: бросает, если авторизация отвергнута или форж недоступен.
    //
    // Почему отдельный метод, а не «упадём на первом чтении очереди»: невалидный
    // токен, обнаруженный лениво, приходит к петле неотличимо от пустой очереди —
    // то есть как «фаза готова к сдаче» (C2). Проверка на старте разводит эти два
    // случая, пока ещё ничего не сделано.
    //
    // Почему в шве, а не в ядре: «авторизован ли форж» — вопрос к форжу.
    // `gh auth status` в ядре означал бы, что петля работает только с GitHub,
    // а он тут один из двух.
    checkAuth(): void;

    // ИМЕНА переменных окружения, в которых живут секреты этой площадки (токен API,
    // токен CLI). Значения ядро берёт из env само и вырезает их из вывода упавшей сессии,
    // из лога и из пуша (#56).
    //
    // Почему спрашивается шов, а не ведётся список в ядре: токен площадки — самый дорогой
    // секрет петли (запись в репозиторий и мердж в `main`), и список, перечисляющий
    // площадки, следующий шов пропустил бы ровно так, как пропускал SourceCraft. Метод
    // обязательный: реализация, забывшая свой секрет, не соберётся, а пустой список
    // отвергает контрактный сьют.
    secretEnvNames(): readonly string[];

    // Открытые issues фазы, ГОТОВЫЕ к работе: без метки `blocked`, автор в
    // allowlist (защита от инъекций через чужие issues, C3), отсортированы по
    // номеру возрастанию (петля берёт первый). Fail-closed: бросает при сбое форжа.
    listReadyIssues(milestone: string): Issue[];

    // ВСЕ открытые issues вехи без фильтров. Назначений ДВА, и это не одно и то же:
    //   1) проверка готовности ФАЗЫ к сдаче (C2: «очередь пуста» ≠ «фаза готова»;
    //      blocked и чужие issues тоже держат фазу открытой);
    //   2) наполнение вехи-НАКОПИТЕЛЯ (#16) — той, которую петля не исполняет вовсе:
    //      по нему считается, влезет ли туда ещё одна карточка. Спрашивают оба канала
    //      адреса — лестница ревью правок и намерение `new-issue` кодер-сессии.
    // Поэтому параметр называется веха, а не фаза: реализация не вправе предполагать,
    // что спрашивают про текущую фазу.
    //
    // Fail-closed: бросает при сбое форжа. Вызывающий вправе трактовать бросок как
    // «не сосчитали» — второе назначение так и делает, и это НЕ ослабление контракта:
    // непрочитанное наполнение там означает «кандидат пропускается», а не «веха пуста».
    listAllOpenIssues(milestone: string): Issue[];

    // Метки ВСЕХ карточек фазы (любого статуса) плоским списком ИМЁН, с повторами —
    // вызывающему нужен ответ «есть ли среди них вот эта», а не структура по карточкам.
    // Fail-closed: сбой обязан бросать, потому что «меток не видно» ядро трактует как
    // зону риска и эскалирует ревью — молчаливый пустой список выдал бы отказ форжа за
    // «сложных задач в фазе нет» (#37).
    listMilestoneLabels(milestone: string): string[];

    // Была ли у фазы хоть одна карточка ЛЮБОГО статуса, включая закрытые (C5).
    //
    // Зачем отдельный вопрос: обе проверки выше отвечают про ОТКРЫТЫЕ карточки, а
    // «открытых нет» одинаково верно и для сделанной фазы, и для фазы, которую ещё не
    // начинали — milestone заведён, задач в нём нет. Второе петля принимала за первое и
    // уходила в цикл сдачи (PR → ревью → правки) по несуществующей ветке.
    //
    // Ответ boolean, а не число: решается ровно «была работа или нет», а счётчик
    // потребовал бы от реализаций честной пагинации там, где хватает одной карточки.
    // Fail-closed: сбой форжа обязан бросать — молчаливое `false` выдало бы сетевой
    // чих за ошибку конфигурации и остановило петлю с неверным диагнозом.
    hasAnyIssues(milestone: string): boolean;

    // Открыта ли веха САМА — не её карточки (#65). Спрашивает адрес накопителя: веха, в
    // которой ноль открытых, одинаково пуста и у свежего тома, и у разобранного, и выбор
    // по наполнению клал находки в закрытую веху, где их не видит никто. Косвенный признак
    // по карточкам («ноль открытых и хоть одна закрытая») ломается на томе, где одну
    // карточку закрыли руками до разбора, — поэтому статус спрашивается у форжа.
    //
    // Статус не кешируется реализацией: веху закрывает сам раннер после мерджа фазы, и
    // ответ, запомненный до этого, врал бы весь остаток прогона.
    // Fail-closed: сбой и ненайденная веха бросают. Вызывающий трактует бросок как «не
    // знаем» и пропускает кандидата — молчаливое `true` вернуло бы ровно #65.
    isMilestoneOpen(title: string): boolean;

    // Тело карточки для кодер-сессии (#50). Fail-closed: пустой ответ вместо отказа — это
    // сессия, работающая по одному заголовку, то есть выдумывающая себе задачу; брейкер
    // `maxNoProgress` погасит петлю тремя итерациями позже, и диагноз будет «нет
    // прогресса», а не «не смогли прочитать карточку».
    getIssue(number: number): IssueDetails;

    // Комментарии PR — все поверхности, на которых форж держит ревью, одной лентой (#37).
    // Считалка находок (`scripts/review-findings.mjs`) раньше ходила за ними в форж сама,
    // и на площадке без его CLI метрика молча обнулялась бы: журнал пуст, петля цела,
    // сигнала нет. «Где лежат комментарии» — вопрос к форжу, поэтому он тут.
    //
    // Fail-closed: сбой чтения обязан БРОСАТЬ. Пустой массив — это «комментариев нет»
    // (легитимно у PR без единой реплики), и подменять им отказ нельзя: ноль находок при
    // прошедшем ревью и ноль находок при недоступном форже в журнале неразличимы.
    // Вызывающий (журнал находок — косметика наблюдаемости) ловит исключение сам.
    listPullRequestComments(prNumber: number): ReviewComment[];

    // Оставить комментарий в PR от имени раннера (#45). Ревью-сессия в форж не ходит —
    // она пишет намерение, а ставит комментарий петля этим методом. Причина та же, что у
    // намерений по карточкам (#40): чтобы сессия могла комментировать сама, ей нужен токен
    // форжа, а с ним и всё остальное, что этим токеном делается, — включая одобрение
    // собственного PR (#2). Плюс переносимость: «оставь замечание к строке» — намерение,
    // `gh api …/pulls/{n}/comments` — способ.
    //
    // Fail-closed: потерянное замечание ревью — это пропущенный дефект и заниженная
    // метрика находок одновременно. Комментарий обязан быть ОПУБЛИКОВАН, а не остаться
    // черновиком: черновик виден только автору, то есть для человека и для счёта его нет
    // (#23 — у SourceCraft это поведение по умолчанию, реализация обязана его перебить).
    //
    // Три вида якоря — три ступени отката ядра (#575): строка → файл → без якоря. Откат
    // ведёт ЯДРО, по отказу реализации: реализация, у которой комментария уровня файла
    // нет, обязана на файловом якоре БРОСИТЬ, а не молча положить его сводкой. Тихая
    // подмена здесь неотличима в логе от «файла нет в диффе» — то есть человек прочитал бы
    // неверную причину, а привязка к месту потерялась бы без следа.
    commentOnPullRequest(prNumber: number, input: NewReviewComment): void;

    // Завести PR ветки фазы в `main` (#46). Раньше это делала отдельная кодер-сессия
    // командой форжа — на площадке, где у сессии нет ни CLI, ни HTTP-доступа, шаг 1 цикла
    // сдачи был невыполним, а худший его исход не стоп, а отчёт «готово» без PR: следующие
    // шаги искали бы несуществующий pull request.
    //
    // Fail-closed: без PR цикл сдачи не начинается вовсе, и «не смогли» обязано быть
    // отказом. Возвращает номер созданного PR либо null, если форж номера не отдал — PR при
    // этом СОЗДАН, поэтому не исключение: повтор создания наплодил бы дубликаты, а номер
    // нужен только для лога (petля всё равно перечитывает PR ветки через
    // `findOpenPullRequest`).
    //
    // Реализация обязана создавать PR ОПУБЛИКОВАННЫМ: у части форжей черновик — поведение
    // по умолчанию (у SourceCraft прямо в спеке `publish: default false`), а черновик для
    // гейта неотличим от «PR нет».
    createPullRequest(input: NewPullRequest): number | null;

    // Открытый PR ветки фазы в `main` или null. Fail-closed на неоднозначности:
    // при >1 открытом PR на ветку возвращает null (не гадать, что мерджить).
    //
    // Сбой форжа (сеть, отказ API, ответ не той формы) — БРОСОК, а не null (#127). null —
    // это ответ форжа «PR нет» (или «больше одного»); сбой, отданный тем же null, для петли
    // неотличим от него: сдача завела бы второй PR, панель показала бы «PR нет». Реализации
    // расходились именно здесь — GitHub глотал сбой, SourceCraft бросал; контрактный сьют
    // проверяет бросок у обеих.
    findOpenPullRequest(branch: string): PullRequest | null;

    // Sha головы PR — та, на которой гейт гоняет чеки и к которой потом прижимает мердж
    // (#49). Раньше её читал сам гейт командой форжа, застрявшей внутри `checksGreen`:
    // барьер `MERGE_PATH_BOUND_SEAMS` честно сторожил состав чеков, а дыра была в том, что
    // гейт ходил в GitHub напрямую. На площадке без его CLI это давало три ретрая и
    // 'not-merged' — фаза не мерджилась НИКОГДА, и TOCTOU-сверка мерджа рушилась заодно:
    // `mergePullRequest` сравнивает голову с той, что «верифицировал» тот же мёртвый вызов.
    //
    // Fail-closed: реализация обязана БРОСИТЬ, если голову прочитать не удалось или форж
    // её не вернул. Пустая строка вместо исключения увела бы гейт в ветку «голова не похожа
    // на sha» — тот же отказ мерджа, но с неверным диагнозом в логе, а диагноз здесь и есть
    // весь смысл: «форж недоступен» чинится не тем, чем «в ответе нет поля».
    //
    // Значение уходит в argv (`git checkout --detach`, `--match-head-commit`), поэтому
    // формат гейт всё равно проверяет сам (`SHA40_RE`) — контракт не отменяет инвариант C3.
    pullRequestHeadSha(prNumber: number): string;

    // Смерджен ли squash-PR ветки фазы в `main`.
    isPhaseMerged(phase: Pick<Phase, 'branch'>): boolean;

    // Номер смердженного PR ветки фазы или null.
    mergedPullRequestNumber(phase: Pick<Phase, 'branch'>): number | null;

    // Squash-мердж PR. `headSha` (если задан и валиден) прижимает мердж к точному
    // sha головы, верифицированному гейтом — закрывает TOCTOU-окно между чеками и
    // мерджем (`--match-head-commit`). Вызывается ядром только после зелёного гейта.
    //
    // Третий параметр — DI-канал исполнения (мутация идёт через argv, не через шелл).
    // Он часть контракта, а не деталь реализации: мердж-путь прокидывает его насквозь,
    // и без него подменить исполнителя в тестах было бы нечем.
    //
    // У `runArgvFn` описаны только обязательные параметры — без хвостового `opts`
    // исполнения. Это не небрежность: параметры функций контравариантны, и попытка
    // описать хвост как `unknown` сделала бы боевую `shArgv` (её хвост типизирован)
    // неприсваиваемой. Более узкое описание совместимо в обе стороны, а `adapters.ts`
    // остаётся без импорта боевых модулей.
    mergePullRequest(
        prNumber: number,
        headSha?: string | null,
        opts?: { runArgvFn?: (file: string, args: string[]) => string },
    ): void;

    // ── Чек PR на стороне форжа (#269), ОБА метода необязательные ───────────
    //
    // Необязательные, и это решение, а не недоделка. Реализация без них означает ровно
    // прежнее поведение: гейт мерджит сразу после своих чеков, а если у форжа есть свой
    // и он красный — форж отвергнет мердж, как отвергал до этой карточки. То есть
    // отсутствие метода НЕ ослабляет мердж-путь, а оставляет его на прежней ступени;
    // обязательность же заставила бы писать реализацию под форж, на котором петля не
    // работает, и проверять её было бы нечем.

    // Вердикт чека PR у форжа. Fail-closed: сбой чтения обязан БРОСИТЬ. «Не смогли
    // спросить» и «чек зелёный» — разные ответы, и подменять первое вторым значит
    // открыть мердж поверх красного прогона на первом же сетевом чихе. Ядро само решает,
    // сколько сбоев подряд считать отказом (`core/forge-checks.ts`).
    pullRequestChecks?(prNumber: number): ForgeChecks;

    // Детали красного прогона: упавший шаг и вырезка его лога. Возвращает `null`, если
    // упавшего шага в прогоне не нашлось (форж покрасил прогон целиком, не назвав шаг) —
    // это не отказ, а «диагноза нет», и вызывающий трактует его как повод звать человека,
    // а не как повод чинить вслепую.
    //
    // Fail-open на самом ЛОГЕ (не прочитали — отдай имя шага и причину вместо текста) и
    // fail-closed на ПРОГОНЕ (не прочитали — бросай): лишать петлю имени упавшего шага
    // из-за недоступного лога незачем, а выдумывать шаг — нельзя.
    redCheckDiagnosis?(run: ForgeCheckRun): ForgeCheckFailure | null;

    // Метка `blocked` на PR ветки фазы. Ставит/снимает ТОЛЬКО раннер (не кодер- и
    // не чини-сессия — #217); fail-open: сбой форжа не роняет петлю.
    addBlockedLabel(branch: string): void;
    removeBlockedLabel(branch: string): void;

    // Косметика после сдачи фазы, fail-open (сбой логируется, петля идёт дальше):
    // закрыть milestone фазы и синхронизировать доску проекта.
    closeMilestone(title: string): void;
    syncBoard(): void;

    // ── Намерения кодер-сессии (#40) ────────────────────────────────────────
    //
    // Сессия в трекер не ходит: она пишет намерение в файл-запрос, петля применяет его
    // ЭТИМИ методами. Отсюда два следствия для контракта:
    //
    //   - все четыре fail-closed. `addBlockedLabel` на PR выше fail-open, потому что там
    //     метка — часть цикла разбора, который повторится; здесь непоставленный `blocked`
    //     означает, что петля возьмёт ту же карточку следующей итерацией и сожжёт её об
    //     ту же стену, а потерянное закрытие оставит фазу вечно открытой;
    //   - параметры — в терминах трекера вообще. Метки приходят ИМЕНАМИ (`complexity:low`),
    //     а не slug'ами: slug — это уже площадочное (у SourceCraft он теряет двоеточие),
    //     и знать про него обязан адаптер, а не ядро и тем более не промпт сессии.

    // Комментарий к карточке от имени раннера.
    commentOnIssue(issue: number, body: string): void;

    // Закрыть карточку. Комментарий НЕ входит: «закрой с комментарием» — это композиция
    // двух намерений, и делает её петля, а не шов. Меньше методов — меньше мест, где
    // реализации разъедутся.
    closeIssue(issue: number): void;

    // Метка `blocked` на КАРТОЧКЕ (не на PR): работа упёрлась в человека, из очереди
    // карточка выпадает, но фазу продолжает держать (C2). Снимает метку человек.
    blockIssue(issue: number): void;

    // Лента комментариев КАРТОЧКИ — тела, по порядку площадки (#125). Читает её ядро ровно
    // в одном месте: сверка начатого намерения `comment`/`close`/`block` по невидимой
    // метке в теле (#94). Без ленты транзиент после ушедшего запроса (обрыв ответа)
    // останавливал петлю стопом `intent-unknown`, хотя исход решался чтением.
    //
    // Fail-closed: сбой чтения БРОСАЕТ, пустой массив — только «комментариев нет». Пустой
    // ответ вместо отказа сверка прочла бы как «эффект не лёг» и повторила бы комментарий
    // вслепую — то есть задвоила бы ровно то, от чего метка и заведена.
    //
    // Необязательный: шов без ленты законен, ядро тогда останавливается с причиной
    // (`unreconcilableWhy`), а не гадает. Обе реализации канона ленту читают.
    listIssueComments?(issue: number): string[];

    // Завести карточку. `labels` — имена, не slug'и (см. выше). Возвращает номер новой
    // карточки либо null, если форж номера не отдал: карточка при этом создана, и молчать
    // об этом нельзя — но и падать не из-за чего, номер нужен только для лога.
    //
    // `milestone` — необязательный АДРЕС карточки, тоже именем (#16). Без него карточки
    // лестницы ревью ложились в общий бэклог ровным слоем: десяток фаз давал десятки
    // почти одинаковых заголовков, в которых уже ничего не найти. Куда лечь адресу —
    // дело реализации (у одного форжа флаг с именем, у другого поле с id), а вот два
    // правила общие: веха не названа — карточка едет как раньше, без адреса; веха названа,
    // но на площадке её нет — карточка ВСЁ РАВНО заводится, без адреса и с записью в лог.
    // Отказ здесь стоил бы находки ради удобства чтения бэклога.
    createIssue(input: {
        title: string;
        body: string;
        labels: readonly string[];
        milestone?: string;
    }): number | null;
};

// ---------------------------------------------------------------------------------
// 2. Гейт: композиция и детерминированный прогон чеков
// ---------------------------------------------------------------------------------
//
// Шов «как гонять чеки» (npm vs cargo/make/gradle). Только ПРОГОН и его вердикт —
// сам мердж и метки принадлежат форжу (`TaskSourceAdapter`); их композицию в цикл
// сдачи делает оркестратор. Контракт хранит деление база/prod и требование
// fail-fast-порядка (дёшево→дорого: security→coverage→e2e) — порядок задаёт автор
// конфига, адаптер его не переставляет.

// Пара [имя, команда] одного чека (`['typecheck', 'npm run typecheck']`).
export type GateCheck = [name: string, command: string];

// Первый красный чек: имя, команда, выжимка вывода — для лога и пуша человеку.
export type RedCheck = { name: string; cmd: string; excerpt: string };

// Вердикт прогона чеков на детач-чекауте точного sha головы PR. Объект (а не голый
// boolean): зелёному нужен `verifiedHead` для `--match-head-commit`, красному —
// `redCheck` для отчёта. Взаимоисключающи: green ⇒ verifiedHead!=null & redCheck=null;
// !green ⇒ verifiedHead=null & redCheck!=null.
export type GateCheckResult = {
    green: boolean;
    verifiedHead: string | null;
    redCheck: RedCheck | null;
};

export type GateAdapter = {
    // Состав чеков для профиля. Прод дропает дедуп-чеки (test↔coverage) и добавляет
    // толстые (security→coverage→e2e), сохраняя fail-fast-порядок; иначе — база.
    resolveChecks(profileName?: string): GateCheck[];

    // Прогнать чеки на детач-чекауте ТОЧНОГО sha головы PR. Детерминированно, агенту
    // на слово не верит. Fail-closed: битый sha/чекаут → бросает (не «считать
    // зелёным»). Зелёный результат несёт верифицированный sha для мерджа.
    runChecks(branch: string, prNumber: number): GateCheckResult;
};

// ---------------------------------------------------------------------------------
// 3. Нотификатор: доставка пуш-событий человеку
// ---------------------------------------------------------------------------------
//
// Шов доставки (сейчас Telegram; кандидаты — Slack/email). Эталон уже изолирован
// (`telegram-notifier.ts`): самостоятельный модуль, DI, свой журнал побочек.

// Контекст доставки, который ядро прокидывает нотификатору насквозь (не часть payload,
// а точки DI): `logFn` — куда писать лог доставки (у эталона — общий `ralph.log`, иначе
// доставка логировалась бы мимо), `execFn` — подменяемый исполнитель (тестовая инъекция
// вместо реальной сети). Оба опциональны: реализация, которой они не нужны, их игнорирует,
// но узаконены в сигнатуре, чтобы реализация фазы 6 (Slack/email) их не потеряла.
export type NotifierDeliveryOpts = {
    logFn?: (msg: string) => void;
    execFn?: (file: string, args: string[], opts?: Record<string, unknown>) => string;
};

export type NotifierAdapter = {
    // Доставить текст события человеку. Fail-open по определению (alert-first): при
    // неудаче доставки ВОЗВРАЩАЕТ false и НИКОГДА не бросает — сбой канала оповещения
    // не должен ронять или блокировать петлю. Пуш-событие — просто текст (без
    // структурированного payload и разметки); `opts` — не данные, а прокинутый ядром
    // контекст доставки (лог/исполнитель), см. NotifierDeliveryOpts.
    notify(text: string, opts?: NotifierDeliveryOpts): boolean;
};

// ---------------------------------------------------------------------------------
// 4. Деплой-проверка: пост-мердж верификация релиза
// ---------------------------------------------------------------------------------
//
// Шов «зелёный ли релиз после мерджа» (сейчас GitHub Actions workflow + HTTP
// health-URL прода; у другого проекта — иной механизм). Классификация fail-closed:
// GREEN только при зелёном воркфлоу И живом проде — иначе барьер стопорит трек.

// Статус ожидания деплой-воркфлоу для sha мерджа.
export type DeployStatus = 'completed' | 'timeout' | 'not-found';

// Исход деплой-воркфлоу для конкретного sha.
export type DeployOutcome = {
    status: DeployStatus;
    conclusion: string | null;
    sha: string;
    url: string | null;
    runId: number | null;
};

// Итог health-чека прода. `reason: 'config'` — health-URL не задан/кривой (даёт
// КРАСНЫЙ деплой, отличимый от «прод не отвечает», а не тихий пропуск).
export type HealthResult = { ok: boolean; status: number; url: string; reason?: 'config' };

// Классифицированный вердикт деплоя: red + человекочитаемая причина (в лог/пуш).
export type DeployVerdict = { red: boolean; reason: string };

export type DeployCheckAdapter = {
    // Есть ли у проекта деплой вообще (#51). Спрашивается ПЕРВЫМ — и ядром после мерджа,
    // и preflight'ом на старте: от ответа зависит, проводить ли пост-мердж проверку и
    // требовать ли `deployCheck.healthUrl`.
    //
    // Почему отдельный вопрос, а не «попробуем и разберём отказ»: fail-closed отвечает на
    // вопрос «релиз зелёный?», и его ответ по умолчанию — красный. Там, где деплоя нет,
    // вопроса нет вовсе, а красный ответ на несуществующий вопрос стопорил трек после
    // КАЖДОГО мерджа. Хуже того, обязательность healthUrl вынуждала вписать в конфиг
    // заведомо ложный адрес, лишь бы пройти старт: барьер, ради прохождения которого врут,
    // уже не защищает — он производит ложь.
    //
    // Чистая функция без побочек: ответ не зависит ни от сети, ни от состояния фазы.
    isEnabled(): boolean;

    // sha коммита мерджа PR в `main`. Fail-closed: бросает, если sha не резолвится
    // (нельзя верифицировать деплой не того коммита).
    mergedShaOf(prNumber: number): string;

    // Ждать завершения деплой-воркфлоу для sha (поллинг с таймаутом). Возвращает
    // исход со статусом completed/timeout/not-found.
    waitForDeployRun(sha: string): DeployOutcome;

    // Проверить здоровье прода (HTTP health-URL с ретраями). `reason:'config'`
    // вместо тихого пропуска при незаданном/кривом URL.
    checkHealth(): HealthResult;

    // Классифицировать исход: GREEN (`red:false`) ТОЛЬКО при зелёном воркфлоу И не
    // явно нездоровом проде; иначе `red:true`. Чистая функция от двух входов.
    classifyOutcome(outcome: DeployOutcome | null, health: HealthResult | null): DeployVerdict;
};

// ---------------------------------------------------------------------------------
// 5. Рантайм кодер-сессии: запуск агента, делающего собственно работу
// ---------------------------------------------------------------------------------
//
// Шов «на чём крутится кодер-сессия». Эталон — Claude CLI: `claude -p` argv,
// permission-mode, `--max-turns`, `--fallback-model`; результат — код возврата +
// собранный stdout+stderr (сканируется на маркер API-лимита, НЕ парсится как JSON —
// сознательно). Специфика провайдера (argv-флаги, формат вывода) живёт ВНУТРИ
// реализации; фаза 6 добавит рантаймы Kimi и OpenAI и AGENTS.md-инструкции для
// не-Claude агентов — они реализуют этот же интерфейс, Claude-путь не меняя.

// Бюджет и модель одной сессии. `maxTurns` — потолок ходов агента; `model`/
// `fallbackModel` провайдер-специфичны (Claude мапит в `--model`/`--fallback-model`;
// `fallbackModel: 'none'`/null — осознанный отказ от фолбэка, honest-стоп).
export type RunOptions = {
    model?: string;
    maxTurns: number;
    fallbackModel?: string | null;
};

// Классификация отказа ЗАПУСКА процесса (#611, milestone «Раннер · Устойчивость к
// отказам») — на границе spawn, где ещё доступен res.error, а не по тексту вывода
// (текстовый путь isRuntimeUnavailable остаётся defense-in-depth поверх, не вместо).
// До #611 spawnClaude/spawnCodex читали у результата spawnSync только status/signal/
// stdout/stderr, НИКОГДА res.error — ENOENT (бинаря нет, идёт автообновление CLI),
// E2BIG (промпт/argv превысил MAX_ARG_STRLEN), EACCES, ENOBUFS были неотличимы от
// обычного `{code: 1, output: '\n'}` честного краха сессии.
//
// - 'runtime-unavailable' — бинаря нет (ENOENT) — транзиент, повторить с backoff;
// - 'arg-too-long'        — E2BIG/«Argument list too long» — детерминированный отказ
//                            ЗАПУСКА, повторов НЕТ, чинить (усечение/stdin, #607);
// - 'spawn-failed'        — иная ошибка транспорта запуска (EACCES/…) — тоже отказ
//                            запуска, не отказ сессии по существу, но и не транзиент —
//                            повторов нет;
// - 'session-failed'      — процесс реально СТАРТОВАЛ и завершился (успешно или нет).
//                            Это не только «res.error отсутствовал»: ревью #612 отнесло
//                            сюда и два исхода С res.error, где процесс всё же отработал —
//                            таймаут (`signal: SIGTERM` + ETIMEDOUT) и переполненный
//                            maxBuffer (`status: 0` + ENOBUFS). Признак старта — живой
//                            status/signal, а не отсутствие ошибки.
export type SpawnFailureKind =
    'runtime-unavailable' | 'arg-too-long' | 'spawn-failed' | 'session-failed';

// Результат одной сессии: код возврата процесса и объединённый вывод (stdout+stderr).
// Оркестратор сканирует `output` на маркер API-лимита и решает про повтор/ожидание —
// это его политика, не рантайма; рантайм лишь честно отдаёт код и вывод.
// `failureKind`/`systemErrorCode` (#611) — структурная классификация отказа запуска.
// Оба поля НЕОБЯЗАТЕЛЬНЫ по существу контракта, а не ради удобства тестов (ревью #612):
// сторонняя реализация шва рантайма может не уметь классифицировать отказ вовсе, и ядро
// обязано работать без них — текстовая эвристика isRuntimeUnavailable остаётся именно на
// этот случай. Боевые реализации заполняют их при `code !== 0` и опускают при успехе
// (`code === 0`): у успеха класса отказа нет.
export type RunResult = {
    code: number;
    output: string;
    failureKind?: SpawnFailureKind;
    systemErrorCode?: string;
};

export type CoderRuntimeAdapter = {
    // Запустить кодер-сессию по промпту в дереве раннера (синхронно). Возвращает код
    // возврата и объединённый вывод. Ожидание API-лимита, ретраи и health туннеля —
    // политика оркестратора вокруг этого вызова, не забота рантайма.
    run(prompt: string, options: RunOptions): RunResult;

    // Рантайм способен запуститься? Зовётся на старте раннера, ДО worktree, установки
    // зависимостей и первой итерации. Fail-closed: бросает, если рантайм не готов, и текст
    // исключения называет причину (бинаря нет, нет прав на исполнение, процесс не ответил).
    //
    // Почему отдельный метод, а не «упадём на первой сессии»: сломанный рантайм (бинарь
    // пропал посреди автообновления) раньше всплывал только кодер-сессией — после монитора,
    // лока, worktree и `npm ci`, и диагноз доставался человеку из лога сессии.
    //
    // Почему в шве, а не в ядре: чем проверяется готовность — вопрос к рантайму. У одного
    // это бинарь, у другого бинарь под чужим именем; `claude --version` в ядре означал бы,
    // что петля знает имя рантайма, — то же правило, по которому в ядре нет `gh`. Парный
    // метод форжа — `TaskSourceAdapter.checkAuth`, и отказы их ядро разводит в тексте:
    // разные причины чинятся разным ремонтом.
    checkAvailable(): void;
};

